// Кто каким голосом говорит в диалоге аудирования (фаза 6.2).
//
// Раньше все реплики озвучивались одним голосом языка, и диалог звучал как
// монолог одного робота: понять, где кончилась одна сторона и началась другая,
// можно было только по расшифровке — а её как раз и нельзя смотреть до ответов.
//
// Голоса берутся из закрытого списка сервера (см. TTS_VOICES в lib/tts.js):
// «a» — основной голос языка, «b» — второй. Распределяем ПО ГОВОРЯЩЕМУ, а не по
// строке: у одного собеседника все реплики звучат одним голосом, даже если он
// говорит подряд. Собеседников в диалоге двое (так просит промпт), но если
// модель добавит третьего — голоса просто пойдут по кругу.
//
// Что именно стоит за «a» и «b», решает сервер: в большинстве языков это два
// разных голоса, в греческом (там голоса неразличимы на слух) — один и тот же
// голос, у второго ниже тон. Здесь эта разница не важна: механика одна.
const VOICES = ["a", "b"];

// Основной голос — тот, которым говорит первая сторона разговора. Отдельным
// именем, потому что по нему отбирают, что можно греть заранее (второй голос
// заранее не готовим — см. prewarmPhrases).
export const PRIMARY_DIALOGUE_VOICE = VOICES[0];

/**
 * Возвращает реплики с добавленным полем voice. Чистая функция: тот же диалог
 * всегда даёт то же распределение — иначе при каждом перерисовывании плеер
 * считал бы содержимое новым и заново ходил за озвучкой.
 *
 * Реплика без пометки говорящего (модель могла её не дать) считается отдельной
 * стороной по своему номеру — голоса тогда просто чередуются.
 */
export function assignDialogueVoices(lines) {
  const bySpeaker = new Map();
  return (Array.isArray(lines) ? lines : []).map((line, i) => {
    const speaker = String(line?.speaker ?? "").trim().toLowerCase() || `#${i}`;
    if (!bySpeaker.has(speaker)) {
      bySpeaker.set(speaker, VOICES[bySpeaker.size % VOICES.length]);
    }
    return { ...line, voice: bySpeaker.get(speaker) };
  });
}
