import { PRIMARY_VOICE } from "./ttsClient.js";

// Кто каким голосом говорит в диалоге аудирования (фаза 6.2).
//
// Раньше все реплики озвучивались одним голосом языка, и диалог звучал как
// монолог одного робота: понять, где кончилась одна сторона и началась другая,
// можно было только по расшифровке — а её как раз и нельзя смотреть до ответов.
// Потом голосов стало два, но выбирались они по ОЧЕРЕДИ говорящих, а генерация
// про голоса ничего не знала — и мужской голос мог сказать о себе «я пришла».
//
// Теперь голос выбирается по ПОЛУ говорящего, а пол приходит вместе с репликой
// из генерации (поле gender, см. lib/comprehension.js). Идентификаторы голосов —
// закрытый список сервера (TTS_VOICES в lib/tts.js):
//   f / m   — голос по полу собеседника;
//   f2 / m2 — ВТОРОЙ собеседник того же пола: тот же голос ниже тоном, чтобы
//             две женщины (или двое мужчин) не звучали одинаково.
// Что именно стоит за каждым, решает сервер: в греческом, например, мужских
// голосов нет вовсе, поэтому там и диалог просят делать между двумя женщинами.
const FEMALE = "f";
const MALE = "m";

// Все идентификаторы, которые сервер понимает (TTS_VOICES в lib/tts.js). Список
// здесь для ПРОВЕРКИ: что бы ни случилось выше, наружу уходит значение из него.
const KNOWN_VOICES = [PRIMARY_VOICE, FEMALE, MALE, `${FEMALE}2`, `${MALE}2`];

// Пол реплики → наш идентификатор. Терпим и слова, и одну букву: поле приходит
// из ответа модели, сервер его уже нормализует, но кэш диалогов на устройстве
// живёт долго и может помнить записи постарше.
function voiceKindOf(gender) {
  const s = String(gender ?? "").trim().toLowerCase();
  if (s.startsWith("m") || s.startsWith("м")) return MALE;
  if (s.startsWith("f") || s.startsWith("w") || s.startsWith("ж")) return FEMALE;
  return null;
}

// Последнее слово перед отправкой: неизвестный голос → ОСНОВНОЙ. Голос — это
// украшение (кто каким тембром говорит), и из-за него озвучка не должна
// отказывать: пусть реплику скажет основной голос языка, чем не скажет никто.
// Тот же принцип, что и на сервере (normalizeVoice/resolveVoice в lib/tts.js) —
// оба конца цепочки деградируют одинаково.
function safeVoice(id) {
  return KNOWN_VOICES.includes(id) ? id : PRIMARY_VOICE;
}

/**
 * Возвращает реплики с добавленным полем voice. Чистая функция: тот же диалог
 * всегда даёт то же распределение — это важно не только для перерисовки, но и
 * для денег: голос входит в ключ общего кэша озвучки, и «плавающее» назначение
 * заставляло бы платить за одну и ту же фразу дважды.
 *
 * Распределяем ПО ГОВОРЯЩЕМУ, а не по строке: у одного собеседника все реплики
 * звучат одним голосом, даже если он говорит несколько раз подряд. Второй
 * собеседник ТОГО ЖЕ пола получает тот же голос ниже тоном (f2/m2).
 *
 * Пола нет (диалог из старого кэша — тогда его ещё не просили) — раздаём полы
 * по очереди появления собеседников, как было до этой правки: первый женский,
 * второй мужской. Реплика без пометки говорящего считается отдельной стороной
 * по своему номеру.
 */
export function assignDialogueVoices(lines) {
  const bySpeaker = new Map(); // собеседник → идентификатор голоса
  const usedByKind = new Map(); // сколько собеседников этого пола уже заняли голос
  const fallback = [FEMALE, MALE];

  return (Array.isArray(lines) ? lines : []).map((line, i) => {
    const speaker = String(line?.speaker ?? "").trim().toLowerCase() || `#${i}`;
    if (!bySpeaker.has(speaker)) {
      const kind =
        voiceKindOf(line?.gender) || fallback[bySpeaker.size % fallback.length];
      const used = usedByKind.get(kind) || 0;
      usedByKind.set(kind, used + 1);
      // Первый собеседник этого пола — обычный голос, следующий — он же ниже
      // тоном. Третьего и дальше (в диалоге их не бывает) сводим туда же.
      bySpeaker.set(speaker, safeVoice(used === 0 ? kind : `${kind}2`));
    }
    return { ...line, voice: safeVoice(bySpeaker.get(speaker)) };
  });
}
