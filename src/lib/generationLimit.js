// ============================================================================
// Суточный лимит генерации карточек: помним, что он выбран.
// ----------------------------------------------------------------------------
// Сам лимит считает СЕРВЕР (см. lib/rateLimits.js и consume_quota в
// supabase/schema.sql), и клиент узнаёт о нём единственным способом — ответом с
// кодом rateLimit. Но знание нужно и ПОСЛЕ ответа: занятие не должно ставить в
// план блок новых слов, если генерировать сегодня уже нечем. Иначе выходит то
// же невыполнимое задание, что и при нехватке мест под активные слова.
//
// Помним ровно факт и ровно до конца тех же UTC-суток: сервер считает квоту по
// календарным суткам UTC, поэтому наступление новых суток само снимает отметку
// — отдельной чистки не нужно, и рассинхрона «у клиента день сменился, а у
// сервера нет» не возникает.
//
// Учёт исчерпания ТЕМ — отдельная история (см. lib/topicExhaustion.js): там про
// конец пула слов, здесь про деньги и квоту. Смешивать их нельзя: тема,
// упёршаяся в лимит, не вычерпана.
// ============================================================================

const KEY = "cardsLimitDay";

function utcDay(date = new Date()) {
  return date.toISOString().slice(0, 10);
}

/** Запомнить, что суточный лимит генерации карточек выбран. */
export function noteCardsLimit() {
  try {
    localStorage.setItem(KEY, utcDay());
  } catch {
    // переполнение хранилища — отметка не критична, молча пропускаем
  }
}

/** Снять отметку: генерация снова прошла, значит квота есть. */
export function clearCardsLimit() {
  try {
    localStorage.removeItem(KEY);
  } catch {
    // ignore
  }
}

/** Выбран ли суточный лимит генерации ПРЯМО СЕЙЧАС (те же UTC-сутки). */
export function isCardsLimitHit() {
  try {
    return localStorage.getItem(KEY) === utcDay();
  } catch {
    return false;
  }
}
