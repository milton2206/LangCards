// Размер шрифта интерфейса (настройка пользователя).
// ----------------------------------------------------------------------------
// ЗАЧЕМ СВОЯ НАСТРОЙКА, а не системный размер шрифта устройства: менять его на
// всём телефоне ради одного приложения человек не должен, а читать крупнее
// хочет именно здесь.
//
// ШАГИ, а не ползунок: произвольное значение позволило бы выставить размер, при
// котором вёрстка едет (длинные немецкие слова, кнопки оценки в повторении).
// Три шага проверены на самых опасных экранах и заведомо не ломают раскладку.
//
// КАК РАБОТАЕТ: множитель уходит в CSS-переменную --font-scale на корне, а
// html { font-size: calc(16px * var(--font-scale)) } (см. index.css) масштабирует
// всё приложение разом — размеры текста везде заданы в rem. Компоненты про эту
// настройку ничего не знают, отдельных правок в них нет.
export const FONT_SCALES = [
  { id: "normal", scale: 1 },
  { id: "large", scale: 1.15 },
  { id: "xlarge", scale: 1.3 },
];

export const DEFAULT_FONT_SCALE = "normal";

export function getFontScale(id) {
  return (
    FONT_SCALES.find((s) => s.id === id) ||
    FONT_SCALES.find((s) => s.id === DEFAULT_FONT_SCALE)
  );
}

/**
 * Применяет выбранный шаг к корню документа. Зовётся из App при загрузке и при
 * смене настройки — как и переключатель темы.
 */
export function applyFontScale(id) {
  if (typeof document === "undefined") return;
  document.documentElement.style.setProperty(
    "--font-scale",
    String(getFontScale(id).scale),
  );
}
