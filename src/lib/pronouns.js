// МЕСТОИМЕНИЯ ДЛЯ ТАБЛИЦЫ СПРЯЖЕНИЯ — на ИЗУЧАЕМОМ языке.
//
// Замечание Димы: «мне не нравится, что при просмотре других форм слов там
// местоимения на русском, надо хотя бы продублировать, потому что мы учим
// I go or I went, а не я go я went».
//
// Он прав: связка «местоимение + форма» и есть то, что человек произносит.
// Для английского это вообще неотделимо — форма «go» без «I» ничего не значит
// и от «we go» неотличима. Раньше в левом столбце стояло только «я/ты/он»,
// то есть половина связки была на родном языке, а половина на изучаемом.
//
// Таблица СТАТИЧЕСКАЯ, в коде: местоимения — закрытый список из шести штук на
// язык, они не меняются, и спрашивать их у модели не за чем (лишний вызов и
// лишний способ ошибиться). Сервер по-прежнему присылает ТОЛЬКО формы —
// формат ответа и кэш спряжений не тронуты.
//
// Ключи совпадают с PERSONS из lib/conjugation.js.
//
// Третье лицо даём парой родов («он/она»), как и подписи на родном: формы у
// них общие, а показать только мужской род значило бы соврать.
// ============================================================================

const PRONOUNS = {
  de: { "1sg": "ich", "2sg": "du", "3sg": "er/sie", "1pl": "wir", "2pl": "ihr", "3pl": "sie" },
  en: { "1sg": "I", "2sg": "you", "3sg": "he/she", "1pl": "we", "2pl": "you", "3pl": "they" },
  el: {
    "1sg": "εγώ",
    "2sg": "εσύ",
    "3sg": "αυτός/αυτή",
    "1pl": "εμείς",
    "2pl": "εσείς",
    "3pl": "αυτοί/αυτές",
  },
  es: {
    "1sg": "yo",
    "2sg": "tú",
    "3sg": "él/ella",
    "1pl": "nosotros",
    "2pl": "vosotros",
    "3pl": "ellos/ellas",
  },
  ru: { "1sg": "я", "2sg": "ты", "3sg": "он/она", "1pl": "мы", "2pl": "вы", "3pl": "они" },
  uk: { "1sg": "я", "2sg": "ти", "3sg": "він/вона", "1pl": "ми", "2pl": "ви", "3pl": "вони" },
};

/**
 * Местоимение изучаемого языка для лица-числа. Языка нет в таблице (или лицо
 * незнакомое) — возвращаем пустую строку: подпись на родном языке в UI
 * остаётся, и таблица работает как раньше. Мягкий фолбэк, а не ошибка.
 */
export function learnPronoun(learnLang, person) {
  return PRONOUNS[learnLang]?.[person] || "";
}
