// ============================================================================
// Числа прогресса по языковой паре — ОДИН расчёт на всё приложение.
// ----------------------------------------------------------------------------
// Показывают их два места: экран статистики (донат + плитки) и полоса под планом
// занятия. Считать в двух местах нельзя: стоит знаменателю или округлению
// разойтись — и приложение начнёт называть РАЗНЫЕ числа одним и тем же словом,
// причём заметит это только тот, кто откроет оба экрана подряд. Поэтому вся
// арифметика живёт здесь, а экраны её только рисуют.
//
// Входы — длины списков текущей пары: сколько слов В ИЗУЧЕНИИ (takenWords) и
// сколько ВЫУЧЕНО (knownWords). Больше для этих чисел ничего не нужно.
// ============================================================================

/**
 * Прогресс по паре: { taken, known, total, knownFraction, knownPercent }.
 *
 * knownFraction/knownPercent — доля выученных СРЕДИ СВОИХ слов, а не «насколько
 * выучен язык»: в знаменателе всё, что человек взял, вместе с ещё не выученным.
 * Так же это число читает и подпись доната на экране статистики.
 */
export function wordStats(takenCount, knownCount) {
  const taken = Math.max(0, Number(takenCount) || 0);
  const known = Math.max(0, Number(knownCount) || 0);
  const total = taken + known;
  const knownFraction = total > 0 ? known / total : 0;
  return {
    taken,
    known,
    total,
    knownFraction,
    knownPercent: Math.round(knownFraction * 100),
  };
}
