// ============================================================================
// НАПРАВЛЕНИЕ ВОПРОСА в повторении: спрашивать слово с изучаемого языка или на
// него. Замечание тестера: «карточка одна, то есть она с одним переводом.
// Допускаю, что помню перевод в ней, так как систематически повторяю. Но как я
// выучу — я это слово реал забуду».
//
// Он описывает известный эффект: при одном и том же направлении человек
// запоминает не слово, а СВЯЗКУ этой карточки с этим ответом — узнаёт её по
// знакомому виду, по длине, по месту в очереди. На карточке помнит, в жизни
// нет. Лечится тем, что одно и то же слово спрашивается то в одну сторону, то
// в другую: угадать «карточку» уже не выходит, приходится знать слово.
//
//   forward — как было: лицо — пример с выделенным словом, оборот — перевод.
//   reverse — лицо: только перевод на родном; человек вспоминает само слово.
//
// ПОЧЕМУ ОТ repetitions, А НЕ ОТ СЛУЧАЙНОГО ЧИСЛА И НЕ ОТ НОМЕРА ШАГА.
// Направление обязано быть устойчивым внутри сессии: «Не помню» возвращает
// слово в очередь через несколько карточек, и если бы направление считалось
// от случайности или от сквозного счётчика заданий, слово вернулось бы уже
// другой стороной — то есть вопрос подменился бы прямо посреди повторения.
// repetitions лежит в состоянии слова и внутри сессии НЕ меняется: «Не помню»
// в ReviewScreen вообще не применяет SRS (слово лишь переносится по очереди),
// а остальные оценки уводят слово из очереди совсем. Значит, пока слово
// крутится в сессии, сторона у него одна.
//
// ПОЧЕМУ ПЕРВОЕ ПОВТОРЕНИЕ — ВСЕГДА ПРЯМОЕ. repetitions — это счётчик подряд
// успешных вспоминаний, у только что взятого слова он 0. Человек ещё не знает
// слова, и спрашивать «как это будет на немецком» бессмысленно: он его просто
// не видел с этой стороны. Чётные значения (0, 2, 4…) — прямое, нечётные
// (1, 3, 5…) — обратное.
//
// Побочно полезное свойство: при «Не помню» nextSrs обнуляет repetitions, так
// что забытое слово возвращается к ПРЯМОМУ направлению — к более лёгкому.
// Переучивание начинается с той же стороны, с которой слово учили изначально.
// ============================================================================

export const FORWARD = "forward";
export const REVERSE = "reverse";

/**
 * Направление вопроса для слова по его состоянию повторения.
 *
 * srs — запись из srsByWord (может отсутствовать у старых слов: тогда 0 → прямое).
 * hasTranslation — есть ли чем спрашивать в обратную сторону. У части старых
 *   записей wordInfo перевода нет вовсе; лицо обратной карточки состоит ТОЛЬКО
 *   из перевода, поэтому без него обратное направление дало бы пустой экран.
 *   В таком случае молча остаёмся на прямом — это рабочий фолбэк, а не ошибка.
 */
export function reviewDirection(srs, hasTranslation = true) {
  if (!hasTranslation) return FORWARD;
  const reps = typeof srs?.repetitions === "number" ? srs.repetitions : 0;
  // Отрицательных значений в данных быть не должно, но модуль по отрицательному
  // числу в JS отрицателен — приводим, чтобы направление не «залипло».
  return Math.abs(reps) % 2 === 1 ? REVERSE : FORWARD;
}
