// ============================================================================
// Проверка известных слов: КОГДА предлагать и КАКИЕ слова брать.
// ----------------------------------------------------------------------------
// Список «Известные» иначе становится кладбищем: слово уходит туда навсегда, и
// через полгода человек забывает его, не заметив. Перенос должен быть
// БЕЗОПАСНЫМ, а не окончательным — в этом половина смысла чек-пойнта «перенести
// в известные». Поэтому приложение само иногда возвращает горсть выученных слов
// на короткую самопроверку.
//
// ЭТО НЕ ВТОРОЙ SRS. Интервалов, лёгкости и серий здесь нет и не будет: у слова
// хранится ровно одна отметка — дата последней проверки (knownCheckedDate). «Помню»
// не пишет больше ничего, ход интервальных повторений известные слова не ведут.
//
// ПОЧЕМУ БЛОК НЕ КАЖДЫЙ ДЕНЬ. Если считать «пора» по одному слову, то после
// разбора шести из полусотни остальные сорок четыре останутся просроченными — и
// блок встанет в план назавтра снова. Это обязаловка, а мы от гонки уходим.
// Поэтому «пора» считается по ВСЕМУ списку сразу: прошла проверка — и следующая
// не раньше чем через две недели.
//
// Отдельного поля «когда была последняя проверка» для этого не нужно: им служит
// самая свежая дата среди известных слов. Проверили сегодня горсть — максимум
// стал сегодняшним, и блок молчит две недели. Меньше хранимого — меньше того,
// что может разъехаться при синхронизации.
// ============================================================================

// Раз в сколько дней предлагать проверку (весь блок целиком, а не слово).
export const KNOWN_CHECK_INTERVAL_DAYS = 14;

// Сколько слов показывать за один заход. Нижняя граница — чтобы блок не
// появлялся ради двух слов (это не занятие, а мелькание); верхняя — чтобы
// проверка оставалась короткой и не превращалась в разбор всего списка.
export const KNOWN_CHECK_MIN = 5;
export const KNOWN_CHECK_MAX = 8;

// Прибавить дни к ключу даты "YYYY-MM-DD" по локальному календарю (days может
// быть отрицательным). Своя копия, а не импорт из useWordLists: модуль должен
// оставаться чистым и не тянуть за собой хук со всем хранилищем.
function shiftDayKey(dayKey, days) {
  const [y, m, d] = String(dayKey).split("-").map(Number);
  if (!y || !m || !d) return dayKey;
  const date = new Date(y, m - 1, d);
  date.setDate(date.getDate() + days);
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  const dd = String(date.getDate()).padStart(2, "0");
  return `${date.getFullYear()}-${mm}-${dd}`;
}

/** Дата последней проверки слова или null, если его ещё не проверяли. */
export function checkedDateOf(word, srsByWord) {
  return srsByWord?.[word]?.knownCheckedDate || null;
}

/**
 * Что показать на проверке известных.
 *
 * Возвращает { due, words, stale }:
 *   due    — пора ли предлагать проверку (блок в занятии);
 *   words  — сама выборка (до KNOWN_CHECK_MAX, дольше всех не проверявшиеся
 *            первыми; никогда не проверявшиеся идут раньше всех);
 *   stale  — сколько всего слов ждут проверки (для отчётов и отладки).
 *
 * due=false при пустом words — блок не ставится. Ручной вход в самопроверку с
 * экрана «Известные» этой функции НЕ спрашивает: там человек сам решил и видит
 * весь список.
 */
export function pickKnownCheck(knownWords, srsByWord, todayKey) {
  const words = Array.isArray(knownWords) ? knownWords : [];
  if (words.length === 0 || !todayKey) {
    return { due: false, words: [], stale: 0 };
  }

  // Граница «давно не проверяли»: всё, что проверено в этот день или раньше.
  const staleBefore = shiftDayKey(todayKey, -KNOWN_CHECK_INTERVAL_DAYS);

  // Самая свежая проверка по списку — она же «когда была последняя проверка».
  let lastCheck = null;
  for (const word of words) {
    const date = checkedDateOf(word, srsByWord);
    if (date && (!lastCheck || date > lastCheck)) lastCheck = date;
  }

  // Проверяли недавно — молчим до срока, сколько бы просроченных ни осталось.
  const restingUntilDue = Boolean(lastCheck && lastCheck > staleBefore);

  const stale = words
    .map((word) => ({ word, date: checkedDateOf(word, srsByWord) }))
    // Никогда не проверявшиеся (date === null) — в начало: они ждут дольше всех.
    .filter(({ date }) => !date || date <= staleBefore)
    .sort((a, b) => {
      if (!a.date && !b.date) return 0;
      if (!a.date) return -1;
      if (!b.date) return 1;
      return a.date < b.date ? -1 : a.date > b.date ? 1 : 0;
    });

  const batch = stale.slice(0, KNOWN_CHECK_MAX).map(({ word }) => word);

  return {
    due: !restingUntilDue && stale.length >= KNOWN_CHECK_MIN,
    words: batch,
    stale: stale.length,
  };
}
