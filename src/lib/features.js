// ============================================================================
// Готовность режимов — переключатели сборки (Vite). Одно место на приложение,
// чтобы «спрятать» и «вернуть» было ОДНИМ действием, а не поиском ветвлений.
// ----------------------------------------------------------------------------
// VITE_MODES_READING_LISTENING — чтение и аудирование.
//   "off" (а также "false" / "0" / "no") — режимы СКРЫТЫ: занятие их не
//   предлагает, входов в хабе «Хочу другое» нет. Сам код режимов, промпты, кэш
//   текстов и диалогов, озвучка и уже взятые из них слова НЕ ТРОГАЮТСЯ: это
//   скрытие на время пересборки, а не удаление.
//   Любое другое значение — и ОТСУТСТВИЕ переменной — режимы включены.
//
// ПОЧЕМУ ПО УМОЛЧАНИЮ ВКЛЮЧЕНО: забытая настройка не должна тихо уносить
// функции. Локальная разработка идёт без переменной вовсе, а спрятать режимы
// можно только осознанно, выставив "off" в нужном окружении.
//
// Значение читается на СБОРКЕ (import.meta.env), поэтому у прод-деплоя и у
// превью оно своё — это разные сборки. В рантайме флаг не меняется.
// ============================================================================

// Написания «выключено», которые встречаются в настройках окружений.
const OFF_VALUES = new Set(["off", "false", "0", "no"]);

function isOff(value) {
  return OFF_VALUES.has(String(value ?? "").trim().toLowerCase());
}

/** Показывать ли чтение и аудирование (по умолчанию — да). */
export const READING_LISTENING_ENABLED = !isOff(
  import.meta.env.VITE_MODES_READING_LISTENING,
);
