// ============================================================================
// Знак LangCards — квадратный пузырь-карточка с кремовой L.
// ----------------------------------------------------------------------------
// Тот же силуэт, что в иконке приложения (public/icon.svg): пузырь — это и
// карточка, и реплика. Здесь знак БЕЗ подложки — он ложится прямо на тёплый фон
// экрана. Цвета фиксированные (терракота + крем), а не тематические: так знак
// выглядит одинаково в тёмной и светлой теме, как на листе фирменного стиля,
// и кремовая буква всегда контрастна на терракоте.
//
// viewBox обрезан по силуэту (88 84 336 368), поэтому знак не тащит за собой
// пустые поля и его удобно ставить в строку с названием.
// ============================================================================

