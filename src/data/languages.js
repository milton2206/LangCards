// ============================================================================
// Единый список языков приложения (фаза 7.1). ОДНО место, где включается и
// выключается изучаемый язык — флагом enabled.
// ----------------------------------------------------------------------------
// Зачем. Владелец проекта не всегда может проверить качество контента на языке
// (например, испанский — нет носителя-проверяющего). Тогда язык выключается
// ОДНОЙ строкой (enabled: false) и исчезает из выбора — и в онбординге, и при
// добавлении/смене пары. Вернуть — так же одной строкой.
//
// ВАЖНО: enabled фильтрует ТОЛЬКО списки выбора новых пар. Существующие
// пользователи выключенного языка ничего не теряют: их строки в user_languages
// (is_active) и весь прогресс в user_words не трогаются, генерация и повторения
// по уже добавленной паре продолжают работать. Выключение = «новым не
// предлагать», а не «отобрать у тех, кто уже учит».
//
// learn — языки, которые можно ИЗУЧАТЬ (со флагом enabled).
// native — языки интерфейса/родные (их набор фиксирован, отдельного гейта нет).
// Подписи берутся из i18n по ключу lang.<id>; здесь только id, эмодзи-флаг и флаг.
// ============================================================================

export const LEARN_LANGUAGES = [
  { id: "de", emoji: "🇩🇪", enabled: true },
  { id: "en", emoji: "🇬🇧", enabled: true },
  { id: "el", emoji: "🇬🇷", enabled: true },
  // Испанский выключен: нет носителя, который проверит качество контента.
  // Вернуть — поменять на enabled: true. Существующие пользователи не затронуты.
  { id: "es", emoji: "🇪🇸", enabled: false },
  { id: "ru", emoji: "🇷🇺", enabled: true },
];

// Родные языки (язык интерфейса). Гейта enabled тут нет — это языки самого UI.
export const NATIVE_LANGUAGES = [
  { id: "ru", emoji: "🇷🇺" },
  { id: "uk", emoji: "🇺🇦" },
  { id: "en", emoji: "🇬🇧" },
];

// Только включённые для изучения языки — для списков выбора пары.
export function enabledLearnLanguages() {
  return LEARN_LANGUAGES.filter((l) => l.enabled);
}

// Включён ли язык для НОВОГО выбора. Для проверки «можно ли предложить язык»,
// а не «есть ли он у пользователя».
export function isLearnLanguageEnabled(id) {
  return LEARN_LANGUAGES.some((l) => l.id === id && l.enabled);
}
