// Перемешивание массива — общий модуль для сервера и клиента.
//
// Заведено ради теста на уровень: модель почти всегда ставит правильный вариант
// первым, и тест становится проходимым без чтения задания. Порядок вариантов
// поэтому задаём мы, а не модель — и делаем это в двух местах: при записи в банк
// (страховка) и при показе (чинит и то, что уже накоплено в банке).
//
// Зависимостей нет намеренно: модуль тянется и во фронтенд-бандл тоже, а
// lib/placement.js туда тащить нельзя — за ним приедут SDK Anthropic и Supabase.

/**
 * Копия массива в случайном порядке (Фишер — Йейтс). Исходный массив не меняется:
 * вызывающий код обычно держит оригинал (например, кэш банка заданий).
 */
export function shuffled(list) {
  const out = Array.isArray(list) ? [...list] : [];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
