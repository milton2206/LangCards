// Нормализация и жёсткое ограничение пользовательской темы. ОДИН источник
// правды: этот модуль без внешних зависимостей импортируют и клиент (обрезает
// перед отправкой), и сервер (перепроверяет перед подстановкой в промпт).
// Это осознанная защита в два эшелона — название темы уходит в промпт генерации,
// поэтому нельзя доверять только клиенту.

// Тема — это КОРОТКОЕ название учебной темы, а не текст. Отсюда жёсткие рамки:
export const MAX_TOPIC_WORDS = 3; // до трёх слов
export const MAX_TOPIC_CHARS = 40; // и не длиннее 40 символов (на случай длинных «слов»)

/**
 * Приводит сырую строку темы к безопасному короткому названию:
 *   • схлопывает любые пробелы/переводы строк в один пробел (перевод строки в
 *     названии — типичный приём подмешать «новую инструкцию» в промпт);
 *   • оставляет не больше MAX_TOPIC_WORDS слов;
 *   • режет по MAX_TOPIC_CHARS символов;
 *   • пустую строку, из одних пробелов или без единой буквы/цифры считает
 *     невалидной и возвращает "" (вызывающий код такую тему не принимает).
 * Возвращает очищенную строку или "".
 */
export function sanitizeTopic(raw) {
  const collapsed = String(raw ?? "")
    .replace(/\s+/gu, " ")
    .trim();
  if (!collapsed) return "";

  let result = collapsed.split(" ").slice(0, MAX_TOPIC_WORDS).join(" ");
  if (result.length > MAX_TOPIC_CHARS) {
    result = result.slice(0, MAX_TOPIC_CHARS).trim();
  }

  // Название без единой буквы или цифры (одни знаки препинания) — не тема.
  if (!/[\p{L}\p{N}]/u.test(result)) return "";
  return result;
}

/** Валидна ли тема как пользовательская (после очистки что-то осталось). */
export function isValidTopic(raw) {
  return sanitizeTopic(raw).length > 0;
}

