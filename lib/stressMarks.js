// Зачистка знаков ударения в сгенерированном тексте карточки.
// ----------------------------------------------------------------------------
// ЗАЧЕМ. Модель ставит ударение наугад и не там: «ладнó» вместо «лáдно», «менé»
// вместо «меня́». В обычном письме русского, украинского, немецкого и английского
// ударение не пишут вовсе, так что любое такое слово — слово с ошибкой. При этом
// в транскрипции ([LAD-na]) ударение стоит верно, и её мы НЕ трогаем.
//
// ГРЕЧЕСКИЙ — ИСКЛЮЧЕНИЕ и обрабатывается отдельно вызывающим кодом: там τόνος
// (ά έ ή ί ό ύ ώ) обязательная часть орфографии, и слово без него написано с
// ошибкой. Здесь его тоже не тронули бы (см. ниже про NFC), но полагаться на
// это не стоит — язык проверяется на входе.
//
// ГЛАВНОЕ ПРАВИЛО ФУНКЦИИ: она СНИМАЕТ ЗНАК, СОХРАНЯЯ БУКВУ. Ни один символ
// слова не должен пропасть или подмениться. Это проверяется здесь же, на выходе
// (см. страховку в конце), потому что цена ошибки высока: испорченное слово
// уезжает в wordInfo вместе с прогрессом повторения, и человек учит его таким.
//
// ТРИ ВИДА МУСОРА, и все три встречаются в реальных ответах модели:
//   1) комбинирующий знак после буквы: «ме́ня» = е + U+0301. Убираем сам знак,
//      буква остаётся своей: «меня». Знаков может быть несколько в одном слове
//      («сто́ло́вая»), и знак бывает после ПОСЛЕДНЕЙ буквы («доктор́»).
//   2) ЛАТИНСКАЯ буква с ударением внутри кириллического слова: «ладнó» — это
//      латинская ó (U+00F3) посреди кириллицы. Просто снять акут мало: осталась
//      бы латинская «o», неотличимая на вид, но чужая для поиска, дедупликации
//      и озвучки. Поэтому такую букву возвращаем в кириллицу по начертанию.
//   3) СЛИТНАЯ кириллическая буква, которой знак сделал ДРУГУЮ БУКВУ. Это была
//      наша собственная беда: NFC собирает «к» + U+0301 в македонскую «ќ», а
//      «г» + U+0301 — в «ѓ» (то же с грависом: «е»+U+0300 → «ѐ», «и»+U+0300 →
//      «ѝ»). После сборки знака отдельно уже нет, снимать нечего, и в слове
//      навсегда оставалась чужая буква: «ру́ќа», «ѓод». Поэтому знак над
//      кириллицей снимаем ДО NFC, а уже собранные буквы возвращаем к основе.
//
// Почему не «снять все диакритики»: испанские á é í ó ú, немецкие ä ö ü ß и
// греческий тонос — это ОРФОГРАФИЯ, а не ударение. Они собраны в один символ
// (NFC), стоят в словах своего алфавита и под правила ниже не попадают.

// Комбинирующие диакритические знаки (U+0300–U+036F): акут, гравис, макрон и
// прочее, что модель вешает на букву отдельным знаком.
const COMBINING = /[̀-ͯ]/g;

// Кириллическая основа + один или НЕСКОЛЬКО знаков подряд. Снимаем знаки прямо
// здесь, до NFC: иначе NFC успеет собрать «к»+U+0301 в «ќ» (см. пункт 3 выше).
const CYRILLIC_STRESSED = /([Ѐ-ӿ])[̀-ͯ]+/g;

// Латинские буквы с акутом → кириллические двойники по НАЧЕРТАНИЮ. Только те,
// что реально путаются: именно их модель подставляет вместо кириллических.
const LATIN_TO_CYRILLIC = {
  á: "а", Á: "А",
  é: "е", É: "Е",
  ó: "о", Ó: "О",
  ú: "у", Ú: "У",
  ý: "у", Ý: "У",
  í: "і", Í: "І", // украинская і; в русском тексте латинская í не встречается
  ć: "с", Ć: "С",
  ḱ: "к", Ḱ: "К",
  ḿ: "м", Ḿ: "М",
  ń: "н", Ń: "Н",
  ṕ: "р", Ṕ: "Р",
  ś: "с", Ś: "С",
  ź: "з", Ź: "З",
};

// Слитные кириллические буквы, которые получаются ИЗ основы и знака ударения,
// → обратно к основе. Все четыре — буквы македонского и сербского; ни в одном
// поддерживаемом языке (ru, uk, de, en, es, el) их не бывает, поэтому встретить
// их в нашем тексте можно только как след от знака ударения. Чиним и уже
// испорченное: старая карточка с «ру́ќа» при следующей зачистке станет «рука».
const COMPOSED_TO_BASE = {
  "ѓ": "г", "Ѓ": "Г", // ѓ Ѓ = г + акут
  "ќ": "к", "Ќ": "К", // ќ Ќ = к + акут
  "ѐ": "е", "Ѐ": "Е", // ѐ Ѐ = е + гравис
  "ѝ": "и", "Ѝ": "И", // ѝ Ѝ = и + гравис
};

const CYRILLIC_RE = /[Ѐ-ӿ]/;
const LATIN_ACUTE_RE = /[áÁéÉóÓúÚýÝíÍćĆḱḰḿḾńŃṕṔśŚźŹ]/gu;
const COMPOSED_RE = /[ѓЃќЌѐЀѝЍ]/gu;

// Сколько знаков ударения стоит в строке — ровно на столько она имеет право
// укоротиться, и ни на символ больше.
function countCombining(text) {
  let n = 0;
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x300 && cp <= 0x36f) n += 1;
  }
  return n;
}

// Языки, где надстрочный знак — ОРФОГРАФИЯ, а не пометка ударения, и снимать
// его нельзя. Пока такой один: греческий (τόνος). Набор живёт здесь, рядом с
// самой зачисткой, а не в вызывающих: решение «этот язык не трогаем» одно на
// всё приложение — и на приёме ответа модели, и при показе старых карточек.
export const STRESS_KEEPING_LANGS = new Set(["el"]);

/**
 * Зачистка С УЧЁТОМ ЯЗЫКА поля: для греческого возвращает текст как есть.
 * Этим пользуются оба конца — сервер (на приёме карточки) и экраны (при показе).
 */
export function stripStressMarksFor(lang, text) {
  return STRESS_KEEPING_LANGS.has(lang)
    ? String(text ?? "")
    : stripStressMarks(text);
}

/**
 * Убирает знаки ударения из текста. Греческий сюда передавать НЕ нужно —
 * решение принимает вызывающий по языку поля (см. stripStressMarksFor).
 *
 * Чистая функция: ни сети, ни состояния — проверяется без вызова модели.
 */
export function stripStressMarks(text) {
  const src = String(text ?? "");
  if (!src) return "";

  // 1) Знак над КИРИЛЛИЦЕЙ снимаем первым — до того, как NFC успеет собрать его
  //    с буквой в другую букву. Знаков подряд может быть несколько.
  let out = src.replace(CYRILLIC_STRESSED, "$1");

  // 2) NFC собирает разложенные последовательности в один символ там, где такой
  //    символ есть: испанское a+акут → á, греческое α+тонос → ά. После этого
  //    отдельным знаком остаётся ровно то, что собрать не во что (например знак
  //    в начале строки, без основы), — его и снимаем.
  out = out.normalize("NFC").replace(COMBINING, "");

  if (CYRILLIC_RE.test(out)) {
    // 3) Латинская буква с ударением внутри кириллического слова — возвращаем
    //    кириллическую. Решаем ПО СЛОВУ: латиница в латинском слове (Bücher,
    //    café) законна и остаётся как есть.
    out = out.replace(/[\p{L}\p{M}]+/gu, (word) => {
      if (!CYRILLIC_RE.test(word)) return word; // слово целиком латинское — не трогаем
      return word.replace(LATIN_ACUTE_RE, (ch) => LATIN_TO_CYRILLIC[ch] || ch);
    });

    // 4) Слитная ѓ/ќ/ѐ/ѝ — след от знака ударения, собранного в букву. Внутри
    //    кириллического текста это всегда мусор (см. COMPOSED_TO_BASE).
    out = out.replace(COMPOSED_RE, (ch) => COMPOSED_TO_BASE[ch] || ch);
  }

  // СТРАХОВКА. Строка имеет право стать короче РОВНО на число снятых знаков —
  // всё остальное значит, что зачистка съела букву. Такое уже случалось бы
  // незаметно: слово уезжает в личный список вместе с прогрессом повторения, и
  // заметить подмену можно только глазами. Поэтому при любом расхождении
  // возвращаем ИСХОДНУЮ строку нетронутой: показать лишний знак ударения
  // не страшно, испортить слово — страшно.
  const expected = [...src].length - countCombining(src);
  if ([...out].length !== expected) return src;

  return out;
}
