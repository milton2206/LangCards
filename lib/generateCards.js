const SOUND_NOT_LETTERS = `ПЕРЕДАВАЙ ЗВУЧАНИЕ, А НЕ БУКВЫ. Транскрипция — это то, как слово ЗВУЧИТ вслух, а не переписывание его букв другим алфавитом. Побуквенная транслитерация — ОШИБКА.`;

function translitRule(learnLang, nativeLang) {
  const learnScript = SCRIPT_OF[learnLang] || "latin";
  const nativeScript = SCRIPT_OF[nativeLang] || "latin";
  const learn = LANGS[learnLang]?.name || learnLang;

  const stress = "Ударный слог — ЗАГЛАВНЫМИ, слоги через дефис.";
  const only =
    "Формат ровно один: смешивать алфавиты и системы записи в одной строке нельзя.";
  const greek = learnScript === "greek" ? ` 
${GREEK_READING}` : "";

  // 1. Изучаемый латинский, родной кириллический — IPA.
  if (learnScript === "latin" && nativeScript === "cyrillic") {
    return `ДВЕ записи произношения подряд, разделённые « · »: сначала ТОЧНАЯ знаками международного фонетического алфавита (IPA), затем ПРИБЛИЗИТЕЛЬНАЯ кириллицей. Обе в квадратных скобках. ${SOUND_NOT_LETTERS}
  • Формат: [IPA] · [кириллица]. Примеры: «appointment» → [əˈpɔɪntmənt] · [э-ПОЙНТ-мэнт]; «to sort out» → [tə ˈsɔːt ˈaʊt] · [тэ СОРТ АУТ]; «nuance» → [ˈnjuːɑːns] · [НЬЮ-анс].
  • ПЕРВАЯ запись — как в словаре, ударение знаком «ˈ» перед ударным слогом. НЕ переписывай слово теми же латинскими буквами: «sort out» → [sort OUT] — это копия написания, а не транскрипция, она не сообщает ничего.
  • ВТОРАЯ запись — приблизительная и нужна тому, кто IPA не учил: кириллицей, слоги через дефис, ударный слог ЗАГЛАВНЫМИ. Она не обязана быть точной — звуков th, æ, ŋ в кириллице нет; передай ближайшим, лишь бы прочитавший вслух был понят.
  • Обе записи обязательны, порядок именно такой. Одну без другой не давай. ${only}`;
  }

  // 2. Изучаемый латинский, родной тоже латинский — латинская запись.
  if (learnScript === "latin") {
    return `подсказка по произношению в квадратных скобках, ЛАТИНСКИМИ БУКВАМИ — читаемая фонетическая запись того, как слово ЗВУЧИТ. ${SOUND_NOT_LETTERS} ${stress} Например: «el ojo» → [el OH-hoh], «ausfallen» → [OUS-fal-en]. Если запись выходит побуквенно равной самому слову, она бесполезна — перепиши так, чтобы она передавала звучание. ${only}`;
  }

  // 3. Письменность у языков одна — подсказывать нечего.
  if (learnScript === nativeScript) {
    return `ВСЕГДА пустая строка "". Родной язык пользователя пользуется той же письменностью, что и ${learn}, — читать слово он умеет, подсказка по произношению не нужна.`;
  }

  // 4. Изучаемый нелатинский — ЛАТИНСКАЯ транслитерация при ЛЮБОМ родном.
  return `подсказка по произношению в квадратных скобках, ЛАТИНСКИМИ БУКВАМИ — читаемая запись того, как слово ЗВУЧИТ, для того, кто НЕ знает письменность ${learn}. ${SOUND_NOT_LETTERS} ${stress} Например: «спасибо» → [spa-SEE-ba], «κοίτα» → [KEE-ta], «πρόβλημα» → [PROV-lee-ma]. Кириллицей эту подсказку не пиши: буквы греческого и кириллицы похожи, и побуквенная подстановка (ο→о, ι→и, υ→у) даёт неверный звук. ${only}${greek}`;
}

// Множественное число нужно существительным — особенно там, где меняются артикль
// и форма (греч. «ο γιατρός» → «οι γιατροί», «το νοσοκομείο» → «τα νοσοκομεία»).
// Берётся в ТОМ ЖЕ запросе генерации, отдельного вызова API нет. Одна формулировка
// на оба режима, чтобы правило не разъезжалось. learn — название изучаемого языка.
function pluralRule(learn) {
  return `для ИСЧИСЛЯЕМЫХ существительных — форма МНОЖЕСТВЕННОГО числа на изучаемом языке (${learn}) вместе с артиклем, если он есть в языке, с ПОЛНОЙ правильной диакритикой (греческий: «ο γιατρός» → «οι γιατροί», «το νοσοκομείο» → «τα νοσοκομεία»; немецкий: «der Arzt» → «die Ärzte»). Если это НЕ существительное (глагол, прилагательное, наречие, выражение) либо множественного числа нет / оно неупотребимо — пустая строка "". Форму не выдумывай: не уверен — пустая строка.`;
}

// Часть речи нужна интерфейсу, чтобы показывать разборы по типу слова (напр.
// таблицу спряжения — только у глаголов). Фиксированный набор тегов, чтобы фронт
// сравнивал по значению. Одна формулировка на оба режима.
const POS_RULE = `часть речи ОДНИМ тегом из списка (латиницей, строчными): "noun" (существительное), "verb" (глагол в любой форме — инфинитив или личная), "adjective" (прилагательное), "adverb" (наречие), "phrase" (устойчивое сочетание из нескольких слов), "other" (прочее). Определи честно; сомневаешься между несколькими — выбери основную часть речи заголовочного слова.`;

// Перевод: НЕ БОЛЬШЕ ДВУХ вариантов, первый — основное значение.
// Раньше правило звучало мягко («естественный перевод»), и модель добирала
// «варианты» через точку с запятой, лишь бы список был длиннее: у «to chew
// someone out» после верного «різко прокритикувати когось» шли выдуманные
// «стримати нападу» и «порушити когось», у «to catch up» — «дати прямий ефір»
// вместо смысла из примера (встретиться после разлуки). Отсюда явные запреты.
//
// ПОЧЕМУ ДВА, А НЕ ОДИН. Один вариант просили тестеры, но одна жёсткая связка
// учит КАРТОЧКЕ, а не слову: у слова бывает несколько значений (замечание
// другого тестера). Два — компромисс: «главное, плюс оттенок». Три и больше
// превращают карточку в словарную статью, и лишнее режется уже на приёме
// (см. limitTranslationVariants).
function translationRule(native, nativeGen) {
  return `перевод на родной язык пользователя (${native}). ЖЁСТКИЕ ПРАВИЛА:
  • Перевод ЦЕЛИКОМ написан на ${native} — ни одного слова и ни одной буквы из третьего языка. Реальный брак: в украинском переводе «це не så важко» слово «så» шведское. Если нужного слова на ${native} не подобрать — переформулируй, но НЕ вставляй чужое.
  • Каждый вариант обязан быть переводом ИМЕННО этого выражения. Не приписывай к переводу посторонние фразы: у «It's not a big deal» вариант «ніч спокійна» не имеет к нему отношения.
  • МАКСИМУМ ДВА ВАРИАНТА, и первым идёт ОСНОВНОЙ — тот, который носитель ${nativeGen} скажет в первую очередь. Второй вариант необязателен: он лишь уточняет оттенок или даёт полноценный синоним В ТОМ ЖЕ значении, и добавляется, только если реально употребим. Разделитель — «; ». ТРЕТЬЕГО ВАРИАНТА НЕ БЫВАЕТ: всё, что сверх двух, будет отброшено. Сомневаешься — оставь один.
  • Перевод обязан соответствовать ТОМУ значению, в котором слово употреблено в поле "example". Пример про встречу после разлуки → перевод про встречу, а НЕ список всех словарных значений.
  • НИКОГДА не добавляй другие значения слова, дословные кальки, придуманные или бессмысленные сочетания и не удлиняй список ради количества. Один точный перевод лучше трёх, из которых два — мусор.
  • Каждый вариант обязан быть осмысленной фразой на ${native}, которую можно встретить в живой речи.`;
}

