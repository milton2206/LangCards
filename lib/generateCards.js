// ПЕРЕВОД ИДИОМЫ — ЭТО ЕЁ ЗНАЧЕНИЕ, А НЕ СУММА СЛОВ. Дефект ОТДЕЛЬНЫЙ от
// REAL_USAGE_RULE: там выражение выдумано, здесь оно НАСТОЯЩЕЕ, а ломается
// перевод. Два случая с прода:
//   «Στα καλά καθούμενα» (греч.) значит «ни с того ни с сего», «внезапно».
//   Модель разобрала оборот по словам («в хорошем сидении») и выдала «когда
//   всё хорошо» — а под этот неверный смысл собрала и пример, поэтому пример
//   вышел бессмысленным. Отсюда требование про пример.
