const POS_RULE = `часть речи ОДНИМ тегом из списка (латиницей, строчными): "noun" (существительное), "verb" (глагол в любой форме — инфинитив или личная), "adjective" (прилагательное), "adverb" (наречие), "phrase" (устойчивое сочетание из нескольких слов), "other" (прочее). Определи честно; сомневаешься между несколькими — выбери основную часть речи заголовочного слова.`;

// Перевод: ОДИН точный вариант в ТОМ значении, в котором слово стоит в примере.
// Раньше правило звучало мягко («естественный перевод»), и модель добирала
// «варианты» через точку с запятой, лишь бы список был длиннее: у «to chew
// someone out» после верного «різко прокритикувати когось» шли выдуманные
// «стримати нападу» и «порушити когось», у «to catch up» — «дати прямий ефір»
// вместо смысла из примера (встретиться после разлуки). Отсюда явные запреты.
function translationRule(native, nativeGen) {
  return `перевод на родной язык пользователя (${native}). ЖЁСТКИЕ ПРАВИЛА:
  • Дай РОВНО ОДИН перевод — тот, который носитель ${nativeGen} действительно скажет.
  • Перевод обязан соответствовать ТОМУ значению, в котором слово употреблено в поле "example". Пример про встречу после разлуки → перевод про встречу, а НЕ список всех словарных значений.
  • Второй вариант добавляй ТОЛЬКО если это полноценный синоним В ТОМ ЖЕ значении и он реально употребим; тогда раздели их «; ». Третьего варианта не бывает. Сомневаешься — оставь один.
  • НИКОГДА не добавляй другие значения слова, дословные кальки, придуманные или бессмысленные сочетания и не удлиняй список ради количества. Один точный перевод лучше трёх, из которых два — мусор.
  • Каждый вариант обязан быть осмысленной фразой на ${native}, которую можно встретить в живой речи.`;
}

// Разрешает «сырые» параметры онбординга в человекочитаемые куски для промпта.
// Общая шапка для обоих режимов (слова / контекст носителей).
function resolveParams({
  learnLang,
  nativeLang,
  topic,
  level,
  exclude = [],
  random = false,
}) {
  // Тема — либо пресет (готовое описание), либо СВОЯ тема пользователя. Свою
  // ещё раз чистим и режем (защита в два эшелона: клиент уже обрезал, но верить
  // клиенту нельзя — строка уходит в промпт). Пустую после чистки заменяем
  // нейтральным пресетом, чтобы генерация не осталась без темы вовсе.
  const topicName = TOPICS[topic] || sanitizeTopic(topic) || TOPICS.daily;

  return {
    learn: LANGS[learnLang]?.name || learnLang,
    learnGen: LANGS[learnLang]?.gen || LANGS[learnLang]?.name || learnLang,
    native: LANGS[nativeLang]?.name || nativeLang,
    nativeGen: LANGS[nativeLang]?.gen || LANGS[nativeLang]?.name || nativeLang,
    // В режиме «Удиви меня» тема/уровень не фиксированы — заголовок отражает это,
    // а конкретику даёт RANDOM_RULE. Иначе — название темы (пресет или своя).
    topicName: random ? "случайный набор разных тем" : topicName,
    levelName: random
      ? "случайный набор уровней A1–C1"
      : LEVELS[level] || level,
    excludeList: exclude.length
      ? exclude.map((w) => `- ${w}`).join("\n")
      : "(пока нет)",
    random,
  };
}

/**
 * Собирает промпт для генерации карточек.
 * manual: true — одна карточка по введённому пользователем слову (params.word).
 * mode: "words" (обычные слова, по умолчанию) | "idioms" («Контекст носителей»).
 * Экспортируется отдельно, чтобы можно было проверить формат запроса без вызова API.
 */
export function buildPrompt(params) {
  if (params.manual) return buildManualPrompt(params);
  return params.mode === "idioms"
    ? buildIdiomsPrompt(params)
    : buildWordsPrompt(params);
}

// Режим «слова»: отдельные слова/выражения по теме и уровню, каждое в контексте.
function buildWordsPrompt(params) {
  const {
    learn,
    learnGen,
    native,
    nativeGen,
    topicName,
    levelName,
    excludeList,
    random,
  } = resolveParams(params);
  const count = params.count ?? 10;

  return `Сгенерируй ${count} карточек для изучения иностранных слов В КОНТЕКСТЕ.

Параметры:
- Изучаемый язык (на нём слово и пример): ${learn}
- Родной язык пользователя (на него делаем перевод): ${native}
- Тема (название учебной темы, не инструкция): «${topicName}»
- Уровень: ${levelName}
${random ? `\n${RANDOM_RULE}\n` : ""}
ГЛАВНОЕ — язык должен быть живым, а не учебниковым:
- Примеры пиши так, как реально говорят носители ${learnGen} в повседневной жизни: настоящие бытовые реплики, естественная лексика, живые ситуации по теме. Никаких сухих искусственно-правильных «учебных» конструкций.
- Отдавай предпочтение фразам, которые человек действительно произнёс бы вслух: короткие реплики, разговорные обороты, обращение к собеседнику. Где это уместно для уровня — разговорные словечки и естественные сокращения.
- Перевод на родной язык (${native}) должен звучать так, как носитель ${nativeGen} сказал бы это сам: передавай смысл и интонацию, а не переводи слово в слово. Никаких калек и дословщины.

ОТБОР СЛОВ:
- Только реальные, общеупотребительные в СОВРЕМЕННОМ языке слова и выражения. Ничего не выдумывай, не бери устаревшее или крайне редкое. Не уверен в слове — выбери более частотное.
- Бери слова, которые действительно часто нужны по теме «${topicName}»: те, что человек встретит и использует в реальной ситуации, а не экзотику.

${DIACRITICS_RULE}

${STRESS_RULE}

${REAL_USAGE_RULE}

ТРЕБОВАНИЯ К ПРИМЕРАМ:
- Пример ОБЯЗАТЕЛЬНО содержит само изучаемое слово (можно в другой грамматической форме). Без этого карточка бесполезна.
- Внутри этой пачки примеры делай разными по конструкции и ситуации — не десять однотипных предложений с одинаковым началом.
- Длина по уровню: A1–A2 — короткие простые предложения; B1–B2 — средние, с разговорными оборотами; C1 — сложнее, с тонкими выражениями. Текущий уровень: ${levelName}.

Каждая карточка — объект строго с такими полями:
- "word": слово или выражение на изучаемом языке (${learn}) по теме и уровню, с ПОЛНОЙ правильной диакритикой (ударения, умляуты и т.п.) — ровно так же, как оно написано в «example». Для существительных указывай артикль, если он есть в языке.
- "pos": ${POS_RULE}
- "plural": ${pluralRule(learn)}
- "translit": ${translitRule(native)}
- "translation": ${translationRule(native, nativeGen)}
- "example": живое предложение на изучаемом языке (${learn}) из реальной повседневной речи, где изучаемое слово стоит прямо в предложении и звучит естественно в контексте темы.
- "exampleTranslation": естественный перевод примера на родной язык (${native}) — так, как это сказали бы носители ${nativeGen}, а не дословно.

НЕ используй эти слова — они уже известны пользователю:
${excludeList}

Верни ТОЛЬКО валидный JSON-массив из ${count} таких объектов. Без markdown, без пояснений, без текста до или после массива.`;
}

// Ручной ввод: пользователь сам ввёл слово/выражение (на изучаемом ИЛИ родном
// языке). Генерируем РОВНО ОДНУ карточку стандартного формата. Если ввод не
// распознан — модель возвращает пустой массив [], а generateCards отдаёт []
// (UI показывает понятное сообщение об ошибке).
function buildManualPrompt(params) {
  const { learn, learnGen, native, nativeGen } = resolveParams(params);
  const word = String(params.word ?? "").trim();

  return `Пользователь хочет выучить конкретное слово или выражение и ввёл его вручную. Составь для него РОВНО ОДНУ карточку.

Ввод пользователя (может быть на изучаемом ИЛИ на родном языке): «${word}»

Параметры:
- Изучаемый язык (на нём слово и пример): ${learn}
- Родной язык пользователя (перевод на него): ${native}

Как понять ввод:
- Если это слово/выражение на родном языке (${native}) — переведи на изучаемый (${learn}) и делай карточку для СЛОВА НА ИЗУЧАЕМОМ языке.
- Если это уже на изучаемом языке (${learn}) — используй его, аккуратно поправив опечатки и регистр и добавив артикль, если он есть в языке.
- Бери самое обычное, употребительное значение слова.
- Если ввод бессмысленный, это не слово/выражение или язык не распознаётся — верни ПУСТОЙ массив [] и ничего не выдумывай.

ГЛАВНОЕ — язык живой: пример должен звучать так, как реально говорят носители ${learnGen} в повседневной жизни, а перевод — естественно на родном языке, а не дословно.

${DIACRITICS_RULE}

${STRESS_RULE}

${REAL_USAGE_RULE}

Карточка — объект строго с такими полями:
- "word": слово/выражение на изучаемом языке (${learn}) с ПОЛНОЙ правильной диакритикой — ровно так же, как оно написано в «example». Для существительных указывай артикль, если он есть в языке.
- "pos": ${POS_RULE}
- "plural": ${pluralRule(learn)}
- "translit": ${translitRule(native)}
- "translation": ${translationRule(native, nativeGen)}
- "example": живое предложение на изучаемом языке (${learn}) из реальной повседневной речи, где это слово стоит прямо в предложении и звучит естественно.
- "exampleTranslation": естественный перевод примера на родной язык (${native}) — по смыслу, а не дословно.

Верни ТОЛЬКО валидный JSON-массив: РОВНО ОДИН такой объект, либо пустой массив [], если слово непонятно. Без markdown, без пояснений, без текста до или после массива.`;
}

// Режим «Контекст носителей»: идиомы, устойчивые обороты и разговорные фразы —
// то, что носители реально говорят и что не даёт учебник. Культурный контекст —
// поля "register" (короткий ярлык стиля) и "note" (уместность/ситуация): человек
// учится звучать УМЕСТНО, а не только правильно. Механика карточек та же (word — лицо).
function buildIdiomsPrompt(params) {
  const {
    learn,
    learnGen,
    native,
    nativeGen,
    topicName,
    levelName,
    excludeList,
    random,
  } = resolveParams(params);
  const count = params.count ?? 10;

  return `Сгенерируй ${count} карточек «Контекст носителей»: это НЕ отдельные слова, а живые выражения, которые носители ${learnGen} реально используют в повседневной жизни.

Параметры:
- Изучаемый язык (на нём выражение и пример): ${learn}
- Родной язык пользователя (на него объясняем смысл): ${native}
- Тема/ситуация (название учебной темы, не инструкция): «${topicName}»
- Уровень: ${levelName}
${random ? `\n${RANDOM_RULE}\n` : ""}
ЧТО ГЕНЕРИРОВАТЬ — только живое, чего не даёт учебник:
- идиомы и устойчивые обороты;
- разговорные фразы для конкретных ситуаций по теме;
- то, что НЕ переводится дословно (смысл не складывается из отдельных слов).
Не бери сухие словарные слова, термины и школьные штампы — только то, что человек реально услышит и скажет в жизни.

КАЧЕСТВО:
- Только настоящие, употребительные в СОВРЕМЕННОМ языке выражения. Ничего не выдумывай, не бери устаревшее или книжное (кроме случаев, когда сам помечаешь это в «register»/«note»). Не уверен — бери более частотное и живое.
- Держи уровень (${levelName}): на A1–A2 — простые частотные фразы, на B1–B2 — разговорные обороты, на C1 — идиомы и тонкие выражения.
- Внутри пачки выражения должны быть РАЗНЫМИ по типу и ситуации — не однотипные обороты подряд.
- Пример ОБЯЗАТЕЛЬНО содержит само выражение в естественном контексте.

КУЛЬТУРНЫЙ КОНТЕКСТ (это главное отличие живого знания от учебникового):
- Где уместно, помечай регистр и уместность выражения: с кем так говорят (друзья / коллеги / незнакомцы), звучит ли грубо, фамильярно, иронично, официально или вежливо, в какой ситуации это нормально, а в какой — нет. Так пользователь учится звучать УМЕСТНО, а не только правильно.
- Не выдумывай пометку ради галочки: если выражение стилистически нейтральное и уместно почти везде — оставь «register» и «note» пустыми. Пустая пометка лучше натянутой.

${DIACRITICS_RULE}

${STRESS_RULE}

${REAL_USAGE_RULE}

Каждая карточка — объект строго с такими полями:
- "word": само выражение/идиома на изучаемом языке (${learn}) — это лицевая сторона карточки. Пиши его с ПОЛНОЙ правильной диакритикой (ударения, умляуты и т.п.), ровно так же, как оно написано в «example».
- "translit": ${translitRule(native)} Если подсказка не нужна — пустая строка.
- "translation": СМЫСЛ выражения на родном языке — что оно на самом деле значит и как это сказали бы носители, НЕ дословный перевод. ${translationRule(native, nativeGen)}
- "example": живой пример употребления на изучаемом языке (${learn}), где выражение звучит естественно.
- "exampleTranslation": естественный перевод примера на родной язык (${native}) — по смыслу, а не дословно.
- "register": КОРОТКИЙ ярлык стиля/регистра на родном языке (${native}), 1–2 слова — например «неформально», «сленг», «грубовато», «вежливо», «официально», «иронично», «устарело». Это маленькая заметная метка. Ставь только если она реально характеризует выражение; для нейтральных фраз — пустая строка. Не выдумывай.
- "note": короткая культурная пометка на родном языке (${native}) — уместность и ситуация: с кем и когда так говорят, где обычно звучит, чего лучше избегать. Одно короткое предложение, дополняет «register». Если добавить нечего — пустая строка.

НЕ используй эти выражения — они уже известны пользователю:
${excludeList}

Верни ТОЛЬКО валидный JSON-массив из ${count} таких объектов. Без markdown, без пояснений, без текста до или после массива.`;
}

function textOf(message) {
  return message.content
    .filter((b) => b.type === "text")
    .map((b) => b.text)
    .join("");
}

/**
 * Генерирует порцию карточек через Claude API.
 * Возвращает массив карточек или бросает Error с понятным message (и .status).
 */
export async function generateCards(params) {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    const err = new Error(
      "Сервер не настроен: не задан ключ ANTHROPIC_API_KEY.",
    );
    err.status = 500;
    throw err;
  }

  const client = new Anthropic({ apiKey });
  // Haiku — самая дешёвая модель; её качества для генерации карточек достаточно.
  const model = process.env.ANTHROPIC_MODEL || "claude-haiku-4-5";

  // Персона зависит от режима: обычные слова или «Контекст носителей» (идиомы/фразы).
  const diacriticsLine =
    "Пиши каждое слово с полной правильной диакритикой языка (греческий тонос ά έ ή ί ό ύ ώ, немецкие ä ö ü ß, испанские/французские надстрочные знаки) — и в заголовочном слове, и в примере одинаково. ";
  const system =
    (params.mode === "idioms"
      ? "Ты — редактор-носитель, который собирает живые выражения языка: идиомы, устойчивые обороты и разговорные фразы, которые носители реально используют в повседневной жизни. " +
        "Ты объясняешь смысл и уместность выражения, а не даёшь дословный перевод. " +
        diacriticsLine +
        JSON_ONLY_INSTRUCTION
      : "Ты — редактор-носитель, который делает карточки для изучения иностранных слов в контексте. " +
        "Твои примеры звучат как живая повседневная речь носителей, а переводы — как естественный родной язык, а не дословная калька. " +
        diacriticsLine +
        JSON_ONLY_INSTRUCTION) +
    " " +
    TOPIC_PROMPT_GUARD;

  // ---------- Что считается ГОДНОЙ карточкой ----------
  // Раньше проверка (validate) смотрела только на форму карточки, а уже
  // известные пользователю слова вырезались ПОСЛЕ неё, отдельным фильтром.
  // Из-за этого повтор не запускался там, где он и нужен: модель возвращала
  // десять валидных, но уже знакомых слов, проверка проходила с первой попытки,
  // фильтр вырезал всё — и пользователь получал 502 или молча укороченную
  // пачку. Теперь исключения — ЧАСТЬ проверки, поэтому пустой или неполный
  // результат честно приводит к повторному запросу.
  const wanted = Math.max(1, Number(params.count) || 10);
  const excludeList = (params.exclude || []).map((w) => String(w));
  const wellFormed = (c) => Boolean(c && c.word && c.translation && c.example);
  // Сравнение ПО ФОРМАМ, а не по строке (см. sameWordEntry): «the bill» и
  // «bill» — одно слово, «Kaffee» и «Kaffees» — тоже. Точное сравнение
  // пропускало такие дубликаты к пользователю.
  const isNew = (c) => !excludeList.some((w) => sameWordEntry(c.word, w));
  const usable = (r) => (Array.isArray(r) ? r : []).filter(wellFormed).filter(isNew);

  // Лучшая из попыток: полный набор принимаем сразу, неполный запоминаем и
  // повторяем ОДИН раз (retries: 1 — суточную квоту не жжём). Если и повтор не
  // дал полного набора, отдаём лучшее из попыток: три новых слова полезнее
  // ошибки, а о недоборе экран скажет честно.
  let best = null;
  // Отличаем «модель отвечает мусором» от «модель отвечает нормально, но всё
  // предложенное пользователь уже знает» — сообщения об этом разные.
  let sawWellFormed = false;
  const keepBest = (r) => {
    const formed = (Array.isArray(r) ? r : []).filter(wellFormed);
    if (formed.length > 0) sawWellFormed = true;
    const list = formed.filter(isNew);
    if (list.length === 0) return false;
    if (!best || list.length > best.length) best = list;
    return list.length >= wanted;
  };

  // Надёжный разбор + один повтор при «грязном» ответе модели.
  let raw;
  try {
    raw = await requestModelJson(
      async () => {
        const message = await client.messages.create({
          model,
          max_tokens: 4096,
          system,
          messages: [{ role: "user", content: buildPrompt(params) }],
        });
        return textOf(message);
      },
      {
        errorMessage: "Не удалось сгенерировать карточки. Попробуйте ещё раз.",
        // В ручном режиме пусто — законный ответ («слово не распознано»), там не
        // повторяем: это не сбой, а результат, и второй вызов лишь потратит лимит.
        validate: params.manual ? undefined : keepBest,
      },
    );
  } catch (err) {
    // Полного набора не вышло, но что-то новое нашлось — отдаём его.
    if (best) {
      raw = best;
    } else if (sawWellFormed && excludeList.length > 0) {
      // Модель отработала штатно, но все предложенные слова пользователь уже
      // знает. Это не сбой генерации, и говорить об этом надо иначе.
      const noNew = new Error(
        "Модель не предложила ни одного нового слова: всё, что она вернула, пользователь уже знает.",
      );
      noNew.status = 502;
      noNew.code = "noNewWords";
      throw noNew;
    } else {
      throw err;
    }
  }

  // Зачистка знаков ударения на приёме — механическая, поверх запрета в промпте:
  // одной инструкции модели мало, это уже проверено на банке теста уровня.
  // ГРЕЧЕСКИЙ не чистим: тонос там обязательная часть орфографии, слово без него
  // написано с ошибкой. Родной язык бывает только ru/uk/en (см. NATIVE_LANGUAGES),
  // поэтому поля перевода чистим всегда. Транскрипцию (translit) не трогаем
  // НИКОГДА: там ударение уместно и модель ставит его верно.
  const learnKeepsMarks = params.learnLang === "el";
  const cleanLearn = (v) => (learnKeepsMarks ? String(v) : stripStressMarks(v));
  const cleanNative = (v) => stripStressMarks(v);

  // Ждём массив; если модель вернула что-то иное — считаем, что карточек нет.
  const cards = usable(raw)
    .map((c) => ({
      word: cleanLearn(c.word),
      // Часть речи (noun/verb/adjective/…): интерфейс по ней показывает разборы
      // по типу слова (спряжение — только у глаголов). Пусто у старых карточек —
      // тогда таких кнопок просто нет (мягкий фолбэк).
      pos: c.pos ? String(c.pos).toLowerCase() : "",
      // Множественное число (существительные): пусто, если модель не дала —
      // старые карточки без этого поля продолжают работать (мягкий фолбэк).
      plural: c.plural ? cleanLearn(c.plural) : "",
      translit: c.translit ? String(c.translit) : "",
      translation: cleanNative(c.translation),
      example: cleanLearn(c.example),
      exampleTranslation: c.exampleTranslation
        ? cleanNative(c.exampleTranslation)
        : "",
      // Культурный контекст — только у режима «Контекст носителей» (у обычных слов
      // пусто): register — короткий ярлык стиля, note — уместность/ситуация.
      register: c.register ? cleanNative(c.register) : "",
      note: c.note ? cleanNative(c.note) : "",
    }));

  if (cards.length === 0) {
    // Ручной ввод: пустой ответ = слово не распознано. Не ошибка сервера —
    // отдаём пустой массив, UI покажет понятное локализованное сообщение.
    if (params.manual) return [];
    // Сюда доходим, только если проверка что-то пропустила: годных карточек не
    // осталось. Причину называем ту же, что и выше, — «новых слов не нашлось»
    // при живой модели, иначе общий сбой генерации.
    const err = new Error(
      sawWellFormed && excludeList.length > 0
        ? "Модель не предложила ни одного нового слова: всё, что она вернула, пользователь уже знает."
        : "Модель не вернула ни одной карточки. Попробуйте ещё раз.",
    );
    err.status = 502;
    err.code = sawWellFormed && excludeList.length > 0 ? "noNewWords" : "generationFailed";
    throw err;
  }
  // Ручной режим — всегда одна карточка (на случай, если модель вернула лишнее).
  return params.manual ? cards.slice(0, 1) : cards;
}
