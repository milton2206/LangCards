// ---------- Транскрипция: ОДИН формат на пару языков ----------
// Правило раньше кончалось развилкой: «привычная фонетическая подсказка
// средствами родного языка (${native}) ИЛИ IPA». Союз «или» оставлял выбор
// модели, и она решала его заново на каждой карточке. Замер по бэкапу
// (700 карточек) показал ровно это: у пар с латинским родным формат ОДИН
// (el-en, ru-en, es-en — по 100% латиницы), а у пар с кириллическим родным их
// три-пять на пару.
//   de-ru: 62% латиница, 31% кириллица, 7% IPA, 1% смесь
//   en-ru: 74% IPA, 12% смесь IPA+кириллица, 7% латиница, 7% кириллица
//   en-uk: 60% кириллица, 30% IPA, 10% латиница
//   el-ru: 57% кириллица, 30% смесь лат+кир В ОДНОЙ строке («и мé́ra»), 7%
//          латиница, 3% IPA, 3% смесь IPA+кириллица
// Отсюда жалобы: Данил (украинский интерфейс) — «транскрипция чужим алфавитом»,
// Дима — «транскрипцию хочу на английском, если я учу английский».
//
// Теперь формат выбирает ТАБЛИЦА В КОДЕ по паре письменностей, а не модель.
// Никаких «или»: на каждую пару ровно одна формулировка.
const SCRIPT_OF = {
  de: "latin",
  en: "latin",
  es: "latin",
  ru: "cyrillic",
  uk: "cyrillic",
  el: "greek",
};

/**
 * Инструкция по полю "translit" для конкретной пары языков.
 *
 * ГЛАВНОЕ ТРЕБОВАНИЕ — ОБЩЕЕ ДЛЯ ВСЕХ ВЕТОК: транскрипция передаёт ЗВУЧАНИЕ,
 * а не буквы. Побуквенное переписывание — ошибка, и именно её модель делала.
 * Три греческих случая с прода, все систематические:
 *   «κοίτα» → [КО-та] вместо [КИ-та]. Диграф «οι» читается «и»; прочитан
 *      побуквенно. Цена ошибки не косметическая: «κότα» — это «курица», то
 *      есть человек заучивает ДРУГОЕ слово.
 *   «χτύπα» → [хТУ-па] вместо [хТИ-па]. Буква «υ» читается «и», а не «у».
 *   «το πρόβλημα» → [то про-ВЛИ-ма]: ударение поставлено на второй слог, хотя
 *      тонос в самом слове стоит на первом — πρόβλημα. Модель проигнорировала
 *      знак, который сама же написала верно.
 * Замер по бэкапу показал, что латинская ветка греческого этим НЕ болеет
 * (el-en: 59 из 59 однословных сошлись по числу слогов, 56 из 56 — по месту
 * ударения), а ломается именно кириллическая. Похоже, дело в родстве
 * алфавитов: пара ο→о, ι→и, υ→у выглядит «очевидной» побуквенно и при этом
 * неверна по звуку. Поэтому правила чтения названы поимённо.
 *
 * ВЫБОР АЛФАВИТА — ТАБЛИЦЕЙ ПО ПАРЕ, а не решением модели. Ветки:
 *
 * 1. ИЗУЧАЕМЫЙ ЛАТИНСКИЙ, РОДНОЙ КИРИЛЛИЧЕСКИЙ (английский для русского) — IPA.
 *    Прошлая попытка (латинская фонетическая запись) провалилась ровно там, где
 *    у английского орфография сама латинская: «sort out» → [sort OUT] — запись
 *    просто повторяет написание заглавными и не сообщает ничего. Кириллица
 *    отпадает по другой причине: она физически не передаёт th, æ, ŋ («ньюансс»,
 *    «глін», «САБ-ву-фер» из бэкапа) — то есть структурно учит неверному
 *    произношению, а это ровно та беда, которую чиним. IPA точен, стоит в любом
 *    словаре (навык переносится за пределы приложения) и никогда не вырождается
 *    в копию написания.
 *
 * 2. ИЗУЧАЕМЫЙ ЛАТИНСКИЙ, РОДНОЙ ТОЖЕ ЛАТИНСКИЙ — латинская фонетическая
 *    запись: читателю она понятна без обучения новым знакам.
 *
 * 3. ОДНА ПИСЬМЕННОСТЬ (русский для украинца) — транскрипции нет вовсе.
 *
 * 4. ИЗУЧАЕМЫЙ НЕЛАТИНСКИЙ (греческий, русский) — ЛАТИНСКАЯ транслитерация при
 *    ЛЮБОМ родном, в том числе кириллическом. Кириллическая ветка была и
 *    оказалась хуже: замер выше — 59/59 и 56/56 у латинской против 9/11 у
 *    кириллической, и все три случая, которые нашёл тестер, из неё.
 *    Причина в родстве алфавитов: подстановка ο→о, ι→и, υ→у выглядит
 *    очевидной и при этом неверна по звуку. Одним правилом в промпте такую
 *    ловушку не закрыть — на банке теста уровня, на выдуманных оборотах и на
 *    ударениях уже видно, что инструкция долю ошибок снижает, но не обнуляет.
 *    Цена ошибки не косметическая: «κότα» — это «курица». Читаемость почти не
 *    страдает: [to PROV-lee-ma] читается не хуже, чем [то ПРО-вли-ма], а врёт
 *    реже.
 */

// Правила чтения греческого: без них модель переписывает буквы. Диграф читается
// ОДНИМ звуком, и ударение стоит там, где тонос, — больше нигде.
const GREEK_READING = `ГРЕЧЕСКИЕ ПРАВИЛА ЧТЕНИЯ (соблюдать обязательно, это звуки, а не буквы):
- «οι», «ει», «υι», а также «η» и «υ» поодиночке — звук «и» (не «ой», не «эй», не «у»): «κοίτα» → [KEE-ta], НЕ [KO-ta] — «κότα» это вообще другое слово, «курица»; «χτύπα» → [KHTEE-pa], НЕ [KHTOO-pa]; «είναι» → [EE-ne].
- «αι» — звук «э»: «παίζω» → [PE-zo], НЕ [PAY-zo].
- «ου» — звук «у»: «τραγούδι» → [tra-GOO-dhi].
- «αυ» и «ευ» — «ав/аф» и «эв/эф» (в перед звонким, ф перед глухим): «αύριο» → [AV-ree-o], «ευχαριστώ» → [ef-ha-ree-STO].
- «γγ», «γκ» — «нг/г»; «μπ» — «б»; «ντ» — «д»; «τσ» — «ц»; «τζ» — «дз».
- «θ» — глухой межзубный (th в think), «δ» — звонкий межзубный (th в this), «γ» перед α/ο/ου — заднеязычный: передавай их ближайшим звуком, но НЕ подставляй побуквенно «т», «д», «г».
- СЛОГИ ОБЯЗАТЕЛЬНО РАЗДЕЛЯЙ ДЕФИСОМ, а ударный слог пиши ЗАГЛАВНЫМИ: [PROV-lee-ma], а не [provleema]. Без разбивки транскрипция нечитаема и не проверяема.
- УДАРЕНИЕ СТОИТ ТАМ, ГДЕ ТОНОС, И БОЛЬШЕ НИГДЕ. Тонос ты пишешь в самом слове — ставь ударение на ТОТ ЖЕ слог: «πρόβλημα» → [PROV-lee-ma], НЕ [prov-LEE-ma]. Число слогов в транскрипции обязано совпадать с числом слогов в слове (диграф — ОДИН слог).`;

const SOUND_NOT_LETTERS = `ПЕРЕДАВАЙ ЗВУЧАНИЕ, А НЕ БУКВЫ. Транскрипция — это то, как слово ЗВУЧИТ вслух, а не переписывание его букв другим алфавитом. Побуквенная транслитерация — ОШИБКА.`;

// ЗАГОЛОВОЧНОЕ СЛОВО ПОКРЫВАЕТСЯ ЦЕЛИКОМ, ВКЛЮЧАЯ АРТИКЛЬ. Замер по бэкапу:
// в 10 карточках из 700 артикль в транскрипции просто пропал — «ο καφές» →
// [ka-FES], «το νερό» → [ne-RO], «η σαλάτα» → [sa-LA-ta]. Артикль — часть
// заголовочного слова, он несёт род, и по такой подсказке человек не научится
// его произносить.
//
// Тем же пунктом чинится вторая мелочь: 12 карточек из 700 склеены дефисом
// целиком («το τσάι» → [to-TSAH-ee], «η υποδοχή» → [i-i-po-tho-HI]). Дефис
// разделяет СЛОГИ ВНУТРИ слова, слова между собой разделяет пробел — иначе
// читать трудно, а машине не видно, где кончается одно слово и начинается
// другое. Отдельного правила заводить не пришлось.
//
// Механической проверки на артикль намеренно НЕТ: ловить его пришлось бы
// самодельным списком транслитерированных артиклей, а такой список на ложные
// срабатывания не проверен. Бракуем только по тому, что измерено.
//
// ПРИМЕРЫ ЗДЕСЬ — ПО ЯЗЫКУ ЗАПРОСА, и это не косметика. Раньше в блоке стоял
// единственный немецкий пример «die Ärztin» → [dee ERTS-tin] — ЛАТИНСКАЯ
// фонетическая запись, то есть формат ветки 2. В паре de→ru (ветка 1) требуется
// [IPA] · [кириллица], и модель получала образец на своём языке в формате,
// который тут же и запрещён. Теперь пример артикля берётся из таблицы под ту
// ветку, в которую он попадает.
function wholeEntry(learnLang, variant, opts = {}) {
  const ex = learnEx(learnLang);
  const article = variant === "dual" ? ex.articleDual : ex.articleLatin;
  // У русского и украинского артиклей нет — требование про артикль там просто
  // не о чем, но служебные слова во фразе остаются, и правило про них нужно.
  // В варианте "targeted" пункт про артикль уходит только языкам с артиклем.
  const articlePart =
    opts.article === false
      ? ""
      : article
    ? ` Если в заголовке стоит артикль, он обязан быть и в транскрипции: ${article}. Пропущенный артикль — ошибка: он часть слова и несёт род.`
    : ` Артиклей в этом языке нет, но служебные слова во фразе — часть заголовка и в транскрипции обязаны быть.`;
  const hyphen = ` СЛОВА РАЗДЕЛЯЙ ПРОБЕЛОМ, а дефис ставь только между СЛОГАМИ ВНУТРИ слова.${withCase(ex.hyphenCase, "Реальный брак")}`;
  return `ПОКРЫВАЙ ВСЁ ЗАГОЛОВОЧНОЕ СЛОВО ЦЕЛИКОМ, ВКЛЮЧАЯ АРТИКЛЬ И СЛУЖЕБНЫЕ СЛОВА.${articlePart}${hyphen}`;
}

function translitRule(learnLang, nativeLang, opts = {}) {
  const learnScript = SCRIPT_OF[learnLang] || "latin";
  const nativeScript = SCRIPT_OF[nativeLang] || "latin";
  const learn = LANGS[learnLang]?.name || learnLang;
  const ex = learnEx(learnLang);

  const stress = "Ударный слог — ЗАГЛАВНЫМИ, слоги через дефис.";
  // РАНЬШЕ ЗДЕСЬ БЫЛО: «Формат ровно один: смешивать алфавиты и системы записи
  // в одной строке нельзя». Для ветки 1 это прямо запрещало то, что она же и
  // требует, — [IPA] · [кириллица] и есть две системы в одной строке. Ловило
  // правило другое: смесь ВНУТРИ одной записи, «и мé́ra» у пары el→ru (30% пары
  // по замеру бэкапа). Теперь запрет сформулирован именно так и двойную запись
  // не отменяет.
  // Смешать алфавиты можно только там, где в игре два алфавита: в варианте
  // "targeted" вторая половина пункта уходит только таким парам.
  const only =
    opts.mix === false
      ? "Держись ПРЕДПИСАННОГО ЗДЕСЬ формата и никакого другого: не заменяй его своей системой записи."
      : "Держись ПРЕДПИСАННОГО ЗДЕСЬ формата и никакого другого: не заменяй его своей системой записи и не мешай алфавиты ВНУТРИ ОДНОЙ записи." +
        withCase(ex.mixCase, "Реальный брак");
  const greek = learnScript === "greek" ? `
${GREEK_READING}` : "";

  // 1. Изучаемый латинский, родной кириллический — IPA.
  if (learnScript === "latin" && nativeScript === "cyrillic") {
    return `ДВЕ записи произношения подряд, разделённые « · »: сначала ТОЧНАЯ знаками международного фонетического алфавита (IPA), затем ПРИБЛИЗИТЕЛЬНАЯ кириллицей. Обе в квадратных скобках. ${SOUND_NOT_LETTERS}
  • Формат: [IPA] · [кириллица]. Примеры: ${ex.dual}.
  • ПЕРВАЯ запись — как в словаре, ударение знаком «ˈ» перед ударным слогом. НЕ переписывай слово теми же латинскими буквами: такая запись повторяет написание и не сообщает ничего.${withCase(ex.copyBad, "Реальный брак")}
  • ВТОРАЯ запись — приблизительная и нужна тому, кто IPA не учил: буквами РОДНОГО языка пользователя (${LANGS[nativeLang]?.name || nativeLang}), слоги через дефис, ударный слог ЗАГЛАВНЫМИ. Примеры выше записаны русскими буквами; если родной язык другой — пиши его буквами по его правилам чтения. Она не обязана быть точной — звуков th, æ, ŋ в кириллице нет; передай ближайшим, лишь бы прочитавший вслух был понят.
  • Обе записи обязательны, порядок именно такой. Одну без другой не давай.
  • ${wholeEntry(learnLang, "dual", opts)} ${only}`;
  }

  // 2. Изучаемый латинский, родной тоже латинский — латинская запись.
  if (learnScript === "latin") {
    return `подсказка по произношению в квадратных скобках, ЛАТИНСКИМИ БУКВАМИ — читаемая фонетическая запись того, как слово ЗВУЧИТ. ${SOUND_NOT_LETTERS} ${stress} Например: ${ex.latin}. Если запись выходит побуквенно равной самому слову, она бесполезна — перепиши так, чтобы она передавала звучание. ${wholeEntry(learnLang, "latin", opts)} ${only}`;
  }

  // 3. Письменность у языков одна — подсказывать нечего.
  if (learnScript === nativeScript) {
    return `ВСЕГДА пустая строка "". Родной язык пользователя пользуется той же письменностью, что и ${learn}, — читать слово он умеет, подсказка по произношению не нужна.`;
  }

  // 4. Изучаемый нелатинский — ЛАТИНСКАЯ транслитерация при ЛЮБОМ родном.
  const lookalike =
    learnScript === "greek"
      ? "Кириллицей эту подсказку не пиши: буквы греческого и кириллицы похожи, и побуквенная подстановка (ο→о, ι→и, υ→у) даёт неверный звук."
      : "Кириллицей эту подсказку не пиши: она нужна тому, кто кириллицы не читает, — переписывать слово теми же буквами бессмысленно.";
  return `подсказка по произношению в квадратных скобках, ЛАТИНСКИМИ БУКВАМИ — читаемая запись того, как слово ЗВУЧИТ, для того, кто НЕ знает письменность ${learn}. ${SOUND_NOT_LETTERS} ${stress} Например: ${ex.latin}. ${lookalike} ${wholeEntry(learnLang, "latin", opts)} ${only}${greek}`;
}

