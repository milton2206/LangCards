function textOf(message) {
  return message.content
    .filter((b) => b.type === "text")
    .map((b) => b.text)
    .join("");
}

/**
 * Генерирует порцию карточек через Claude API.
 * Возвращает массив карточек или бросает Error с понятным message (и .status).
 */
export async function generateCards(params) {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    const err = new Error(
      "Сервер не настроен: не задан ключ ANTHROPIC_API_KEY.",
    );
    err.status = 500;
    throw err;
  }

  const client = new Anthropic({ apiKey });
  // Haiku — самая дешёвая модель; её качества для генерации карточек достаточно.
  const model = process.env.ANTHROPIC_MODEL || "claude-haiku-4-5";

  // Персона зависит от режима: обычные слова или «Контекст носителей» (идиомы/фразы).
  const diacriticsLine =
    "Пиши каждое слово с полной правильной диакритикой языка (греческий тонос ά έ ή ί ό ύ ώ, немецкие ä ö ü ß, испанские/французские надстрочные знаки) — и в заголовочном слове, и в примере одинаково. ";
  const system =
    (params.mode === "idioms"
      ? "Ты — редактор-носитель, который собирает живые выражения языка: идиомы, устойчивые обороты и разговорные фразы, которые носители реально используют в повседневной жизни. " +
        "Ты объясняешь смысл и уместность выражения, а не даёшь дословный перевод. " +
        diacriticsLine +
        JSON_ONLY_INSTRUCTION
      : "Ты — редактор-носитель, который делает карточки для изучения иностранных слов в контексте. " +
        "Твои примеры звучат как живая повседневная речь носителей, а переводы — как естественный родной язык, а не дословная калька. " +
        diacriticsLine +
        JSON_ONLY_INSTRUCTION) +
    " " +
    TOPIC_PROMPT_GUARD;

  // ---------- Что считается ГОДНОЙ карточкой ----------
  // Раньше проверка (validate) смотрела только на форму карточки, а уже
  // известные пользователю слова вырезались ПОСЛЕ неё, отдельным фильтром.
  // Из-за этого повтор не запускался там, где он и нужен: модель возвращала
  // десять валидных, но уже знакомых слов, проверка проходила с первой попытки,
  // фильтр вырезал всё — и пользователь получал 502 или молча укороченную
  // пачку. Теперь исключения — ЧАСТЬ проверки, поэтому пустой или неполный
  // результат честно приводит к повторному запросу.
  const wanted = Math.max(1, Number(params.count) || 10);
  const excludeList = (params.exclude || []).map((w) => String(w));
  const wellFormed = (c) => Boolean(c && c.word && c.translation && c.example);
  // Сравнение ПО ФОРМАМ, а не по строке (см. sameWordEntry): «the bill» и
  // «bill» — одно слово, «Kaffee» и «Kaffees» — тоже. Точное сравнение
  // пропускало такие дубликаты к пользователю.
  const isNew = (c) => !excludeList.some((w) => sameWordEntry(c.word, w));

  // Зачистка знаков ударения нужна ещё ДО проверок ниже: сравнивать слово с
  // примером надо по чистым формам, иначе знак в одном из полей выглядел бы
  // расхождением. Греческий не чистим (тонос — орфография), поля перевода
  // чистим всегда: родной язык бывает только ru/uk/en.
  const cleanLearn = (v) => stripStressMarksFor(params.learnLang, v);
  const cleanNative = (v) => stripStressMarks(v);
  // Перевод: чистим ударения и режем до двух вариантов, попутно отмечая, у
  // каких слов пришлось резать (число уходит в лог — см. ниже).
  const trimTranslation = (c, noted) => {
    const full = cleanNative(c.translation);
    const short = limitTranslationVariants(full);
    if (short !== full) noted.push(String(c.word));
    return short;
  };

  // ЦЕЛОСТНОСТЬ СЛОВА. Заголовочное слово обязано отзываться в СВОЁМ ЖЕ примере
  // (грубый поиск следа — см. wordEchoedIn). Ловится карточка, собранная не из
  // тех кусков, и слово, искажённое до неузнаваемости.
  //
  // ЧЕГО ЭТА ПРОВЕРКА НЕ ЛОВИТ, и это надо знать: слово, испорченное ОДИНАКОВО
  // во всех полях («пок» и в слове, и в примере, и в транскрипции), расхождения
  // не даёт — механически придраться не к чему. Не ловится и «апартама́ты» при
  // верном примере: от «апартаменты» оно отличается серединой слова, а начало
  // общее. Строгая сверка форм тут не спасает: на реальных карточках она
  // забраковала 15% ЗДОРОВЫХ (сильные глаголы, греческий аорист, составные
  // слова), а эти два случая всё равно пропустила. Поэтому против искажений
  // работает правило промпта (WORD_INTEGRITY_RULE), а проверка держит нижнюю
  // границу — «карточка вообще не про это слово».
  //
  // Ручной ввод и просмотр слова из текста ПРОПУСКАЕМ намеренно: там слово
  // выбирает человек, а модель отдаёт его СЛОВАРНУЮ форму, которая законно
  // отличается от формы в предложении («ging» в тексте → «gehen» на карточке).
  // ГЛАГОЛЫ из проверки выведены: у них основа меняется законно и сильнее всего
  // — отделяемые приставки (abheben → «hebt … ab»), греческий аорист (τρώω →
  // «έτρωγες»), русское чередование (хотеть → «хочешь»). Замер на реальных
  // карточках: без этого исключения проверка бракует именно их, и все такие
  // отбраковки — ложные.
  const checksIntegrity = !params.manual && !params.lookup;
  const isSound = (c) =>
    !checksIntegrity ||
    String(c.pos || "").toLowerCase() === "verb" ||
    wordEchoedIn(cleanLearn(c.example), cleanLearn(c.word));

  // ЧИСТОТА ПЕРЕВОДА: чужой алфавит внутри кириллического перевода — брак
  // («це не så важко»). Проверяем ВЕЗДЕ, включая ручной ввод: замер на 693
  // реальных переводах дал ноль ложных срабатываний, а цена пропуска высокая —
  // человек учит чужое слово как часть перевода.
  const isCleanTranslation = (c) =>
    !hasForeignScript(cleanNative(c.translation), params.nativeLang);

  // УДАРЕНИЕ В ГРЕЧЕСКОЙ ТРАНСКРИПЦИИ. Тонос в самом слове однозначно задаёт
  // ударный слог, транскрипция отмечает его ЗАГЛАВНЫМИ — две пометки сверяются
  // механически (см. lib/translitCheck.js). Расходятся — карточка бракуется:
  // «η συζήτηση» → [ee see-zee-TEE-see] учит неверному ударению, а частота
  // такого около 5% (одна ошибка на два прокрута порции).
  //
  // Почему БРАКУЕМ, а не только пишем в лог: на 700 карточках бэкапа проверка
  // дала НОЛЬ ложных срабатываний, то есть здоровых карточек не теряем.
  // Покрытие около 19% греческих (нужны и тонос, и слоговая разбивка) — это не
  // «мало пользы», а пятая часть случаев даром. Остальное держит правило чтения
  // в промпте (GREEK_READING).
  const isStressRight = (c) =>
    !stressMismatch(params.learnLang, c.word, c.translit);

  const usable = (r) =>
    (Array.isArray(r) ? r : [])
      .filter(wellFormed)
      .filter(isNew)
      .filter(isSound)
      .filter(isCleanTranslation)
      .filter(isStressRight);

  // НАКОПЛЕНИЕ, а не «лучшая попытка». Раньше из двух попыток бралась та, что
  // длиннее (best), и вторая попытка пропадала целиком: шесть новых слов в
  // первой и пять ДРУГИХ во второй давали шесть, а не одиннадцать. Теперь
  // годные карточки складываются со всех попыток, а дубли внутри пачки
  // отсекаются тем же сравнением по формам.
  const collected = [];
  // Что модель уже предлагала в ЭТОМ запросе (годное и негодное). Уходит в
  // исключения повторной попытки: без этого повтор шёл тем же промптом и
  // приносил тот же список — главная причина, по которой недобор не добирался.
  const seenWords = [];
  // Отличаем «модель отвечает мусором» от «модель отвечает нормально, но всё
  // предложенное пользователь уже знает» — сообщения об этом разные.
  let sawWellFormed = false;
  // Сколько карточек забраковано и почему — по всем попыткам. Числа уходят в
  // лог: тихая отбраковка, о которой никто не знает, хуже самой проблемы.
  let brokenWords = [];
  let dirtyTranslations = [];
  // Забраковано по расхождению ударения с тоносом (только греческий).
  const stressOff = [];
  const keepBest = (r) => {
    const formed = (Array.isArray(r) ? r : []).filter(wellFormed);
    if (formed.length > 0) sawWellFormed = true;
    for (const c of formed) seenWords.push(String(c.word));
    const fresh = formed.filter(isNew);
    for (const c of fresh) {
      if (!isSound(c)) brokenWords.push(String(c.word));
      else if (!isCleanTranslation(c)) dirtyTranslations.push(String(c.word));
      else {
        const off = stressMismatch(params.learnLang, c.word, c.translit);
        if (off) stressOff.push(off);
      }
    }
    for (const c of fresh
      .filter(isSound)
      .filter(isCleanTranslation)
      .filter(isStressRight)) {
      if (!collected.some((x) => sameWordEntry(x.word, c.word))) collected.push(c);
    }
    return collected.length >= wanted;
  };

  // ПРОСИМ С ЗАПАСОМ. Часть пачки всегда съедают исключения (пользователь уже
  // знает эти слова) и проверки выше, поэтому «попросить ровно 20» означало
  // «получить 9». Просим больше нужного, а лишнее не пропадает: столько,
  // сколько не уместилось в пачку, клиент кладёт в запас на следующий раз
  // (см. useCards). Потолок нужен из-за max_tokens и стоимости.
  const askModel = Math.min(
    MAX_MODEL_BATCH,
    wanted + Math.max(BATCH_MARGIN_MIN, Math.ceil(wanted * BATCH_MARGIN_RATIO)),
  );
  // Потолок ответа считаем от размера пачки: 20 греческих карточек — это уже
  // ~2900 токенов (замер по реальным данным), и с запасом прежние 4096 их
  // просто обрезали бы. Ручной ввод и прогрев остаются короткими.
  const maxTokens = Math.min(8192, 1200 + askModel * TOKENS_PER_CARD);

  // Надёжный разбор + один повтор при «грязном» ответе модели.
  let attempt = 0;
  let raw;
  try {
    raw = await requestModelJson(
      async () => {
        attempt += 1;
        // ПОВТОР ПРОСИТ ДРУГОЕ. Раньше вторая попытка уходила тем же промптом с
        // тем же списком исключений — модель честно возвращала примерно тот же
        // набор, и добора не происходило. Теперь всё, что она уже предложила,
        // добавляется в исключения, а сверху идёт прямое требование дать другие
        // слова.
        const attemptParams =
          attempt > 1 && seenWords.length > 0
            ? { ...params, count: askModel, exclude: [...excludeList, ...seenWords] }
            : { ...params, count: askModel };
        const prompt =
          attempt > 1 ? `${buildPrompt(attemptParams)}\n\n${RETRY_RULE}` : buildPrompt(attemptParams);
        const message = await client.messages.create({
          model,
          max_tokens: maxTokens,
          system,
          messages: [{ role: "user", content: prompt }],
        });
        return textOf(message);
      },
      {
        errorMessage: "Не удалось сгенерировать карточки. Попробуйте ещё раз.",
        // В ручном режиме пусто — законный ответ («слово не распознано»), там не
        // повторяем: это не сбой, а результат, и второй вызов лишь потратит лимит.
        // В ручном режиме и в прогреве повтора нет: пусто — законный ответ
        // («слово не распознано» / «нечего греть»), а неполный набор для
        // прогрева нормален — недостающее доспросится по тапу. Второй вызов
        // только потратил бы лимит и деньги.
        validate: params.manual || params.lookup ? undefined : keepBest,
      },
    );
  } catch (err) {
    // Полного набора не вышло, но что-то новое накопилось — отдаём накопленное.
    if (collected.length > 0) {
      raw = collected;
    } else if (sawWellFormed && excludeList.length > 0) {
      // Модель отработала штатно, но все предложенные слова пользователь уже
      // знает. Это не сбой генерации, и говорить об этом надо иначе.
      const noNew = new Error(
        "Модель не предложила ни одного нового слова: всё, что она вернула, пользователь уже знает.",
      );
      noNew.status = 502;
      noNew.code = "noNewWords";
      throw noNew;
    } else {
      throw err;
    }
  }

  // Отбраковка — вслух, а не молча: без строки в логе такой брак невозможно ни
  // заметить, ни измерить. Отдельно пишем недобор: по нему видно, упирается ли
  // пул выражений на этом уровне (тогда нужны темы, а не правки промпта).
  if (brokenWords.length > 0) {
    console.warn(
      `[cards] забраковано по расхождению слова с примером: ${brokenWords.length} ` +
        `(${params.learnLang}: ${brokenWords.slice(0, 10).join(", ")})`,
    );
  }
  if (dirtyTranslations.length > 0) {
    console.warn(
      `[cards] забраковано по чужому алфавиту в переводе: ${dirtyTranslations.length} ` +
        `(${params.nativeLang}: ${dirtyTranslations.slice(0, 10).join(", ")})`,
    );
  }
  if (!params.manual && !params.lookup && collected.length < wanted) {
    console.warn(
      `[cards] недобор: просили у модели ${askModel}, годных ${collected.length} из нужных ${wanted} ` +
        `(${params.learnLang}/${params.mode || "words"}, исключений ${excludeList.length}, попыток ${attempt})`,
    );
  }

  // Зачистка знаков ударения на приёме (cleanLearn/cleanNative объявлены выше,
  // рядом с проверками) — механическая, поверх запрета в промпте: одной
  // инструкции модели мало, это уже проверено на банке теста уровня.
  // Транскрипцию (translit) не трогаем НИКОГДА: там ударение уместно и модель
  // ставит его верно.
  // Ждём массив; если модель вернула что-то иное — считаем, что карточек нет.
  // Источник — НАКОПЛЕННОЕ за все попытки. Брать raw нельзя: там лежит только
  // последний ответ модели, и всё, что нашла первая попытка, потерялось бы.
  // Сколько переводов пришлось подрезать до двух вариантов: по этому числу
  // видно, держит модель правило или игнорирует его (см. лог ниже).
  const trimmedTranslations = [];
  const cards = usable(collected.length > 0 ? collected : raw)
    .map((c) => ({
      word: cleanLearn(c.word),
      // Часть речи (noun/verb/adjective/…): интерфейс по ней показывает разборы
      // по типу слова (спряжение — только у глаголов). Пусто у старых карточек —
      // тогда таких кнопок просто нет (мягкий фолбэк).
      pos: c.pos ? String(c.pos).toLowerCase() : "",
      // Множественное число (существительные): пусто, если модель не дала —
      // старые карточки без этого поля продолжают работать (мягкий фолбэк).
      plural: c.plural ? cleanLearn(c.plural) : "",
      translit: c.translit ? String(c.translit) : "",
      translation: trimTranslation(c, trimmedTranslations),
      example: cleanLearn(c.example),
      exampleTranslation: c.exampleTranslation
        ? cleanNative(c.exampleTranslation)
        : "",
      // Культурный контекст — только у режима «Контекст носителей» (у обычных слов
      // пусто): register — короткий ярлык стиля, note — уместность/ситуация.
      register: c.register ? cleanNative(c.register) : "",
      note: c.note ? cleanNative(c.note) : "",
    }));

  if (stressOff.length > 0) {
    console.warn(
      `[cards] забраковано по ударению (расходится с тоносом): ${stressOff.length} ` +
        `(${params.learnLang}: ${stressOff
          .slice(0, 10)
          .map(
            (x) =>
              // Во фразе виновато одно слово — называем и его, и саму карточку,
              // иначе по логу непонятно, что именно забраковано.
              `${x.phrase ? `${x.phrase} / ` : ""}${x.word} → [${x.translit}] ` +
              `тонос ${x.tonos}, заглавные ${x.caps}`,
          )
          .join("; ")})`,
    );
  }

  if (trimmedTranslations.length > 0) {
    console.warn(
      `[cards] переводов подрезано до двух вариантов: ${trimmedTranslations.length} ` +
        `(${params.nativeLang}: ${trimmedTranslations.slice(0, 10).join(", ")})`,
    );
  }

  if (cards.length === 0) {
    // Ручной ввод: пустой ответ = слово не распознано. Не ошибка сервера —
    // отдаём пустой массив, UI покажет понятное локализованное сообщение.
    if (params.manual) return [];
    // Прогрев фоновый: пустой ответ — не повод для ошибки, экран просто
    // продолжит спрашивать переводы по тапу, как раньше.
    if (params.lookup) return [];
    // Сюда доходим, только если проверка что-то пропустила: годных карточек не
    // осталось. Причину называем ту же, что и выше, — «новых слов не нашлось»
    // при живой модели, иначе общий сбой генерации.
    const err = new Error(
      sawWellFormed && excludeList.length > 0
        ? "Модель не предложила ни одного нового слова: всё, что она вернула, пользователь уже знает."
        : "Модель не вернула ни одной карточки. Попробуйте ещё раз.",
    );
    err.status = 502;
    err.code = sawWellFormed && excludeList.length > 0 ? "noNewWords" : "generationFailed";
    throw err;
  }
  // Ручной режим — всегда одна карточка (на случай, если модель вернула лишнее).
  return params.manual ? cards.slice(0, 1) : cards;
}
