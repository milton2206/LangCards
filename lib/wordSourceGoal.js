// ============================================================================
// Общая логика «строим вокруг активных слов пользователя + источник слов»
// (mine/mixed/new) для генерации 6.1 (текст чтения) и 6.2 (диалог аудирования).
// ----------------------------------------------------------------------------
// Это ГЛАВНОЕ в обоих режимах: и текст, и диалог должны собираться вокруг слов,
// которые пользователь реально учит, — иначе понимание проверять не на чем.
// Чтобы чтение и аудирование вели себя ОДИНАКОВО, семантика источника живёт в
// одной точке: mine — преимущественно свои слова, mixed — свои + новое, new —
// незнакомая лексика под уровень. Отличается только существительное («текст» /
// «диалог»), которое подставляется в формулировки.
// ============================================================================

/** Приводит источник к допустимому: неизвестное молча трактуем как «смешанно». */
export function normalizeSource(source) {
  return ["mine", "mixed", "new"].includes(source) ? source : "mixed";
}

/**
 * Эффективный источник: «Мои слова» без единого взятого слова строить не из
 * чего — трактуем как «Смешанно» (в UI это сопровождается подсказкой).
 */
export function effectiveSource(source, knownLen) {
  const src = normalizeSource(source);
  return src === "mine" && knownLen === 0 ? "mixed" : src;
}

/**
 * Возвращает блок «ГЛАВНОЕ …» для промпта генерации и эффективный источник.
 * nouns — формы существительного артефакта: { acc: винительный, gen: родительный }
 * («текст»/«текста» для чтения, «диалог»/«диалога» для аудирования).
 */
export function buildWordSourceGoal({
  source,
  known = [],
  levelName,
  newPercent,
  nouns,
}) {
  const acc = nouns?.acc || "текст";
  const gen = nouns?.gen || "текста";
  const effective = effectiveSource(source, known.length);
  const knownList = known.map((w) => `- ${w}`).join("\n");

  let goalBlock;
  if (effective === "mine") {
    // ПРЕИМУЩЕСТВЕННО знакомые слова (а не строго только): цель — закрепление,
    // но если своих слов не хватает на связную фразу, недостающее добираем
    // новым по минимуму, а знакомые остаются большинством.
    goalBlock = `ГЛАВНОЕ — преимущественно знакомые слова (закрепление):
- Строй ${acc} ПРЕИМУЩЕСТВЕННО из слов пользователя (список ниже): они должны составлять БОЛЬШИНСТВО значимых слов ${gen}.
- Если знакомых слов не хватает на связное, естественное предложение — добери недостающее новыми словами уровня ${levelName}, но добавляй новое ТОЛЬКО ПО НЕОБХОДИМОСТИ и ПО МИНИМУМУ. Новое ради разнообразия не подмешивай, знакомые остаются большинством.
- Повторять знакомые слова — нормально: цель в том, чтобы закрепить уже взятое. Форму слова меняй свободно (падеж, число, время).

Слова пользователя (основа ${gen}):
${knownList}`;
  } else if (effective === "new") {
    // Намеренно незнакомые слова под уровень — расширение словаря.
    goalBlock = known.length
      ? `ГЛАВНОЕ — новая лексика под уровень (расширение словаря):
- Пиши ${acc} из НЕЗНАКОМОЙ пользователю, но полезной лексики строго уровня ${levelName}.
- НЕ используй слова, которые пользователь уже знает (список ниже) — подбери другие, новые для него.
- Держись уровня строго: новое, но по силам, без редкого и вычурного.

Слова, которых ИЗБЕГАТЬ (они уже знакомы пользователю):
${knownList}`
      : `ГЛАВНОЕ — новая лексика под уровень (расширение словаря):
- Своих слов у пользователя пока нет: дай полезную лексику строго уровня ${levelName}.
- Бери частотное и нужное, держись уровня строго — новое, но по силам, без вычурного.`;
  } else {
    // mixed — прежнее поведение по умолчанию.
    goalBlock = known.length
      ? `ГЛАВНОЕ — узнавание знакомого + немного нового:
- Обязательно вплети в ${acc} слова, которые пользователь уже учит (список ниже). Возьми столько из них, сколько получится вплести ЕСТЕСТВЕННО, — это главный смысл ${gen}. Форму слова меняй свободно (падеж, число, время), это нормально.
- Если слов в списке мало — вплети ВСЕ, какие получится, а остальное добери частотной лексикой этого уровня.
- Незнакомых слов — примерно ${newPercent}% ${gen}: заметная доля нового, чтобы расширять словарь, но ${acc} всё ещё читался легко.

Слова пользователя (вплетай их):
${knownList}`
      : `ГЛАВНОЕ — ${acc} строго под уровень:
- Своих слов у пользователя пока нет, поэтому ЕДИНСТВЕННЫЙ ориентир — ${levelName}. Держись его строго.
- Бери самую частотную и полезную лексику этого уровня: ${acc} должен читаться легко и целиком состоять из слов, которые на этом уровне реально нужны.
- Не усложняй ради интереса: лучше простое и живое, чем редкое и вычурное. Все слова здесь для пользователя новые — это нормально.`;
  }

  return { goalBlock, effective };
}
