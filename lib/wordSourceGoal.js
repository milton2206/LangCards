// ============================================================================
// ОБЩИЕ БЛОКИ ПРОМПТА для генерации 6.1 (текст чтения) и 6.2 (диалог
// аудирования). Обе генерации устроены одинаково, поэтому формулировки живут
// здесь в одном экземпляре — иначе они разъезжаются, и правку получает только
// один из двух режимов. Отличается только существительное («текст» / «диалог»),
// которое подставляется в формулировки.
// ----------------------------------------------------------------------------
// Выбор источника слов (мои/смешанно/новые) убран — осталось ОДНО поведение,
// равное прежнему «смешанно»: узнавание уже изучаемых слов + немного нового под
// тему и уровень. И текст, и диалог собираются вокруг слов, которые пользователь
// реально учит, — иначе понимание проверять не на чем.
// ============================================================================

// Сколько заголовков недавних сюжетов отдаём модели «чтобы не повторяться» —
// предохранитель стоимости: короткие заголовки, не сами тексты/диалоги.
export const MAX_RECENT_TITLES = 6;

/**
 * Блок промпта «не повторяй недавние сюжеты» — ОБЩИЙ для генерации текста чтения
 * (6.1) и диалога аудирования (6.2): и там, и там модель без подсказки штампует
 * один и тот же сценарий по теме. Даём ей заголовки недавних сюжетов этой темы и
 * просим ДРУГОЙ сценарий. Это только заголовки (не сами тексты) — дёшево. Пустой
 * список → пустая строка: промпт остаётся прежним, как без этой фичи.
 * nounPlural — «тексты»/«диалоги»; participants — «герои»/«участники».
 */
export function buildDiversityBlock(
  recentTitles,
  {
    nounPlural = "тексты",
    participants = "герои",
    // Заголовки недавних материалов ДРУГОГО формата на ту же тему (для чтения —
    // диалоги аудирования, для диалога — тексты чтения). Нужны, чтобы текст и
    // диалог по одной теме/словам НЕ совпадали: механизм генерации общий, а
    // результаты должны расходиться.
    crossTitles = [],
    crossNounPlural = "",
  } = {},
) {
  const clean = (arr) =>
    (Array.isArray(arr) ? arr : [])
      .map((s) => String(s ?? "").trim().replace(/\s+/g, " ").slice(0, 80))
      .filter(Boolean)
      .slice(0, MAX_RECENT_TITLES);
  const recent = clean(recentTitles);
  const cross = clean(crossTitles);
  if (recent.length === 0 && cross.length === 0) return "";

  let block = `\nНЕ ПОВТОРЯЙ НЕДАВНИЕ СЮЖЕТЫ (важно для разнообразия):\n`;
  if (recent.length) {
    block += `- В этой теме у пользователя уже были такие ${nounPlural} (заголовки): ${recent
      .map((r) => `«${r}»`)
      .join(", ")}.\n`;
  }
  if (cross.length) {
    block += `- А ещё по этой теме были такие ${crossNounPlural || "материалы"} (заголовки): ${cross
      .map((r) => `«${r}»`)
      .join(", ")}. Новый материал должен ОТЛИЧАТЬСЯ и от них — другой сюжет, даже если тема и слова те же. Не пересказывай их своими словами.\n`;
  }
  block += `- Придумай ДРУГОЙ сценарий в рамках той же темы: иное место, иная ситуация, иные ${participants}, иная завязка. Например, тема «работа» — это не только первый день, но и собеседование, увольнение, конфликт с коллегой, повышение, совещание, командировка.
- Не пересказывай прежние сюжеты и не бери тех же персонажей.\n`;
  return block;
}

/**
 * Блок «только реально существующие выражения» — ограда против выдуманных
 * оборотов в тексте чтения и в репликах диалога.
 *
 * ЗАЧЕМ. Оба промпта сами просят живую речь носителей, а описание уровня C1
 * (см. LEVELS в generateCards.js) прямо требует идиом и устойчивых выражений.
 * Требование верное — но без ограды модель начинает конструировать обороты по
 * образцу чужого языка и подавать их как настоящие. В карточках это уже
 * ловилось (там свой такой же запрет), а в текстах и диалогах ограды не было
 * вовсе, хотя условия те же.
 *
 * ЗДЕСЬ ХУЖЕ, ЧЕМ В КАРТОЧКЕ. Выражение в тексте ТАПАБЕЛЬНО: тап → шторка →
 * «Взять оборот в изучение» → слово уходит в активные с историей повторений,
 * попадает в списки и через knownWords вплетается в следующие тексты. Человек
 * месяцами учит фразу, которой нет, а приложение само подсовывает её снова.
 *
 * Примеры названы поимённо намеренно: на конкретных случаях модель держит
 * правило заметно лучше, чем на общей формулировке (проверено на карточках).
 *
 * into — куда попадает выражение («в текст» / «в реплику»); learnGen — родительный
 * падеж названия изучаемого языка, native — название родного.
 */
export function buildRealUsageBlock({ into, learnGen, native }) {
  return `ТОЛЬКО РЕАЛЬНО СУЩЕСТВУЮЩИЕ ВЫРАЖЕНИЯ:
- Идиомы и устойчивые обороты уместны, но ${into} попадают ТОЛЬКО те, которые носители ${learnGen} действительно так говорят. Это проверяется не по смыслу, а по факту употребления.
- НЕ переводи идиомы с других языков буквально и не собирай похожие по образцу. Английское «not my cup of tea» НЕ превращается в русское «не мой чай» — такого оборота нет, это выдумка, а не перевод. Не изобретай и конструкций вроде «попадать на точку».
- Нет естественного оборота для нужной мысли — скажи её обычными словами. Пропустить оборот лучше, чем выдумать: человек может тапнуть по нему и взять его себе в изучение, и тогда он будет учить несуществующую фразу как настоящую.
- То же и в переводе на ${native}: перевод обязан быть фразой, которую на нём реально говорят, а не калькой с ${learnGen}.
`;
}

/**
 * Возвращает блок «ГЛАВНОЕ …» для промпта генерации — ЕДИНСТВЕННОЕ поведение
 * (прежнее «смешанно»): вплетаем уже изучаемые слова + немного нового под уровень.
 * nouns — формы существительного артефакта: { acc: винительный, gen: родительный }
 * («текст»/«текста» для чтения, «диалог»/«диалога» для аудирования).
 */
export function buildWordSourceGoal({ known = [], levelName, newPercent, nouns }) {
  const acc = nouns?.acc || "текст";
  const gen = nouns?.gen || "текста";
  const knownList = known.map((w) => `- ${w}`).join("\n");

  const goalBlock = known.length
    ? `ГЛАВНОЕ — узнавание знакомого, но БЕЗ перегруза:
- Вплети в ${acc} НЕСКОЛЬКО слов из тех, что пользователь уже учит (список ниже) — примерно 3–5 штук, и именно те, что ложатся в сюжет ЕСТЕСТВЕННО. НЕ пытайся вставить все слова из списка: втиснутые силой слова ломают связность и делают материалы похожими друг на друга. Нескольких знакомых слов для узнавания достаточно.
- Форму слова меняй свободно (падеж, число, время) — это нормально.
- Остальной ${acc} — обычная частотная лексика этого уровня (${levelName}); незнакомого — небольшая доля (около ${newPercent}%), чтобы расширять словарь, но ${acc} читался легко и связно.
- ПРИОРИТЕТ РАЗНООБРАЗИЯ НАД ПОКРЫТИЕМ: если выбор между «вставить побольше моих слов» и «сделать ${acc} естественным, живым и НЕ похожим на прежние материалы», — всегда выбирай второе. Лучше 3 моих слова в новом непохожем сюжете, чем 8 в натянутом и похожем на прошлый ${acc} или на диалог/текст той же темы.

Слова пользователя (вплети НЕСКОЛЬКО, а не все):
${knownList}`
    : `ГЛАВНОЕ — ${acc} строго под уровень:
- Своих слов у пользователя пока нет, поэтому ЕДИНСТВЕННЫЙ ориентир — ${levelName}. Держись его строго.
- Бери самую частотную и полезную лексику этого уровня: ${acc} должен читаться легко и целиком состоять из слов, которые на этом уровне реально нужны.
- Не усложняй ради интереса: лучше простое и живое, чем редкое и вычурное. Все слова здесь для пользователя новые — это нормально.`;

  return { goalBlock };
}
